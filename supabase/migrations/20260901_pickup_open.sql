-- שער האיסוף — "אפשר כבר לבוא למוקד".
--
-- 🔴 בלי זה אין דרך לומר למשפחה מתי לבוא. המוקד שלה מוצג לה מרגע
-- הבחירה, אבל הכתובת המדויקת והשעות היו שמורות בטבלת המוקדים ולא
-- הגיעו אליה בשום ערוץ — היא ידעה *לאן* אבל לא *מתי*.
--
-- ⚠️ שער שלישי ונפרד, ולא שימוש חוזר ב-centers_open: בחירת המוקדים
-- נסגרת דווקא לפני שהאיסוף נפתח. איחוד השניים היה מציג את שעות
-- האיסוף כבר בשלב הבחירה — כלומר שולח משפחות למוקד שבועיים מוקדם
-- מדי, לפני שהכרטיסים בכלל הוטענו.
--
-- ⚠️ שדה של *החלוקה* ולא של המוקד: הפתיחה היא החלטה אחת לכל החלוקה
-- ("הכרטיסים מוכנים, אפשר להתחיל לחלק"), ולא החלטה נפרדת לכל מוקד.
alter table public.distributions
  add column if not exists pickup_open boolean not null default false;

comment on column public.distributions.pickup_open is
  'שער האיסוף: כשדולק, המשפחה רואה בפורטל ושומעת בטלפון את הכתובת המדויקת ושעות האיסוף של המוקד שבחרה. נפרד מ-centers_open — האיסוף נפתח אחרי שהבחירה נסגרת.';

-- הודעה חופשית שמוצגת לצד השעות (למשל "יש להביא תעודת זהות").
--
-- ⚠️ טקסט חופשי ברמת החלוקה ולא נוסח קבוע בקוד: ההנחיות משתנות מחג
-- לחג, ושינוי שלהן אינו אמור לדרוש פריסה.
alter table public.distributions
  add column if not exists pickup_note text;

comment on column public.distributions.pickup_note is
  'הודעה חופשית שמוצגת למשפחה לצד שעות האיסוף. NULL = לא מוצגת.';
