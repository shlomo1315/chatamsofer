-- ─────────────────────────────────────────────────────────────────────────────
-- סגירת ההרשאות הפתוחות: mail / widows / newsletter
--
-- הרקע: משתמש שסומן לו "הלוואות בלבד" ראה בפועל גם את תיבות הדואר, את
-- אלמנות ויתומים ואת הניוזלטר. שלושה כשלים הצטברו:
--   1. הסרגל נהג לפי "מחלקה ללא סימון = מותרת".
--   2. widows ו-newsletter כלל לא הופיעו במסך ההרשאות, ולכן לעולם לא סומנו
--      ותמיד נפלו לברירת המחדל המתירנית הזו.
--   3. 'mail' לא היה מפתח הרשאה בכלל — מסלולי הדואר בדקו "איש צוות?" בלבד.
--
-- הקוד תוקן (ברירת מחדל סגורה + requireMailAccess), אך התיקון לבדו אינו
-- משנה נתונים קיימים: פרופיל שאין בו את המפתחות האלה ימשיך להיות מוכרע
-- לפי היעדרם. המיגרציה הזו כותבת אותם במפורש.
--
-- ההחלטה שהתקבלה: 'none' לכל מי שאינו מנהל. מי שזקוק לגישה — המנהל מסמן
-- לו ידנית במסך ההגדרות. סגירה ואז פתיחה מבוקרת, ולא להפך.
--
-- ⚠️ אינה נוגעת במפתחות קיימים: coalesce שומר כל ערך שכבר נקבע, כך
--    שהרצה חוזרת בטוחה ואינה דורסת סימונים ידניים שנעשו אחריה.
-- ⚠️ מנהלים (role = 'admin') מדולגים — הם עוקפים את המטריצה בקוד ממילא,
--    וכתיבת 'none' להם הייתה מטעה את מי שיקרא את הטבלה.
-- ⚠️ משתמשי "מייל בלבד" מקבלים גם הם 'none' ב-mail — וזה מכוון: הקוד
--    (requireMailAccess) מתיר להם גישה מתוקף ההגדרה עצמה, בלי סימון.
-- ─────────────────────────────────────────────────────────────────────────────

update public.profiles
set permissions = coalesce(permissions, '{}'::jsonb)
  || jsonb_build_object(
       'mail',       coalesce(permissions -> 'mail',       '"none"'::jsonb),
       'widows',     coalesce(permissions -> 'widows',     '"none"'::jsonb),
       'newsletter', coalesce(permissions -> 'newsletter', '"none"'::jsonb)
     )
where role is distinct from 'admin'
  and (
    permissions is null
    or permissions -> 'mail'       is null
    or permissions -> 'widows'     is null
    or permissions -> 'newsletter' is null
  );
