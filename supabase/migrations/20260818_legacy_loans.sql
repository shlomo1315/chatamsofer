-- ─────────────────────────────────────────────────────────────────────────────
-- הלוואות מהמערכת הקודמת ("שטרות חתם סופר").
--
-- 1,148 הלוואות היסטוריות שקיימות רק בקובץ אקסל. בלעדיהן, מזכיר שבוחן בקשה
-- חדשה אינו יודע שלמשפחה כבר הייתה הלוואה — וזו בדיוק השאלה הראשונה שנשאלת.
--
-- 🔴 השיוך למשפחה נעשה **לפי ת"ז בזמן קריאה**, ולא בהצמדה חד-פעמית ל-
-- beneficiary_id בזמן הייבוא. שתי סיבות:
--   1. יש שלוש נקודות רישום של מוטב במערכת (register, public-register, טופס
--      אדמין). הצמדה בזמן רישום הייתה מחייבת קוד שיוך בכל אחת מהן, ונקודה
--      רביעית שתיווצר בעתיד הייתה שוכחת אותו בשקט.
--   2. משפחה שנרשמת *אחרי* הייבוא צריכה לראות את ההיסטוריה שלה מיד. חיפוש
--      לפי ת"ז בכל טעינה נותן זאת מאליו, וגם למפרע לכל מי שנרשם קודם.
-- לכן אין כאן beneficiary_id, ואין טריגר סינכרון.
--
-- ⚠️ id_number נשמר **מנורמל לספרות בלבד** (digits_only). באקסל ובמסד ת"ז
-- מופיעה עם ומבלי אפס מוביל, ולעיתים עם מקפים — והשוואה גולמית הייתה מחמיצה
-- התאמות אמיתיות. הנרמול נעשה בייבוא, והחיפוש משווה מול אותה צורה.
-- ─────────────────────────────────────────────────────────────────────────────

create table if not exists public.legacy_loans (
  id uuid primary key default gen_random_uuid(),

  -- מספר התיק במערכת הקודמת. מזהה טבעי לצורך זיהוי מול המקור.
  file_number text,
  -- שם הקרן ("חתם סופר"). כרגע ערך יחיד, אך נשמר לקראת קרנות נוספות.
  fund text,

  -- ── מפתח השיוך ──
  -- ⚠️ ספרות בלבד. ראה הערת הפתיחה.
  id_number text,
  borrower_name text,

  -- פרטי קשר כפי שהופיעו במערכת הקודמת. לתיעוד בלבד — לא מקור אמת, כי
  -- הכתובת והטלפון העדכניים הם אלה שבכרטסת המוטב.
  address text,
  city text,
  phone text,
  email text,

  -- ── שני הסכומים, במכוון בנפרד ──
  --
  -- 🔴 approved_amount = מה שהמשרד אישר. taken_amount = מה שנלקח בפועל.
  -- באקסל 637 לקחו ו-511 אושרו ומעולם לא לקחו — כמעט מחצית. איחוד שני
  -- השדות לאחד היה מוחק את ההבחנה הזו, שהיא בדיוק מה שצריך להיראות.
  --
  -- ⚠️ taken_amount NULL = אושר ולא נלקח. אפס אינו אותו דבר: הוא הופיע
  -- באקסל בשתי שורות ופירושו "בוצע בסכום אפס", לא "אין נתון".
  --
  -- ⚠️ באקסל הסכום שבוצע רשום שלילי (-9000) — כך נראה חיוב בהנהלת חשבונות.
  -- נשמר כערך מוחלט, כי המסך מציג סכום הלוואה ולא רשומה חשבונאית.
  approved_amount numeric,
  taken_amount numeric,
  installments integer,

  -- ── תיעוד המקור ──
  -- ⚠️ שורת המקור באקסל, כדי שניתן יהיה לחזור אליה בבירור מול המשרד.
  source_row integer,

  -- 🔴 שורה שנערכה ידנית מסומנת, וטעינה חוזרת של אותו אקסל **מדלגת עליה**.
  -- בלי זה, כל ייבוא חוזר היה דורס בשקט את התיקונים הידניים.
  manually_edited boolean not null default false,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by text
);

-- ── השאילתה החמה: היסטוריית ההלוואות של משפחה ──
-- רצה בכל טעינת כרטסת הלוואה, פעמיים (ת"ז הבעל ות"ז האישה).
create index if not exists legacy_loans_id_number_idx
  on public.legacy_loans (id_number);

-- מניעת כפילות בטעינה חוזרת של אותו אקסל.
--
-- ⚠️ על file_number ולא על ת"ז: לאותו אדם יכולות להיות כמה הלוואות (5 מקרים
-- באקסל), ומפתח על ת"ז היה מוחק את השנייה. מספר התיק ייחודי לכל הלוואה.
--
-- ⚠️ חלקי (where file_number is not null): שורה שתיווצר ידנית בעתיד ללא
-- מספר תיק אינה אמורה להיחסם.
create unique index if not exists legacy_loans_file_number_idx
  on public.legacy_loans (file_number)
  where file_number is not null;

comment on table public.legacy_loans is
  'הלוואות מהמערכת הקודמת. השיוך למשפחה דינמי לפי id_number ואינו מוצמד ל-beneficiary_id — כדי שמוטב שנרשם אחרי הייבוא יראה את ההיסטוריה שלו מיד.';
comment on column public.legacy_loans.id_number is
  'ת"ז מנורמלת לספרות בלבד. מפתח השיוך למשפחה.';
comment on column public.legacy_loans.approved_amount is
  'הסכום שאושר על ידי המשרד.';
comment on column public.legacy_loans.taken_amount is
  'הסכום שנלקח בפועל. NULL = אושר ומעולם לא נלקח (511 מתוך 1,148 באקסל המקורי).';
comment on column public.legacy_loans.manually_edited is
  'סומן אחרי עריכה ידנית. ייבוא חוזר מדלג על שורות כאלה כדי לא לדרוס תיקונים.';
