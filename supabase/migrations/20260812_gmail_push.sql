alter table public.gmail_accounts
  -- ⚠️ ה-historyId של ההתראה האחרונה *שטופלה*, נפרד מ-last_history_id
  -- (הסמן של הסנכרון עצמו).
  --
  -- 🔴 למה שתי עמודות ולא אחת: Pub/Sub מוסר *לפחות* פעם אחת, ואותה התראה
  -- חוזרת אחרי כל תקלת רשת. הבחנה בין "עד לאן סונכרנתי" לבין "איזו התראה
  -- כבר ראיתי" היא מה שמונע סנכרון מיותר בכל מסירה חוזרת — ושריפת מכסת
  -- ה-API של Gmail בעקבותיו.
  add column if not exists last_push_history_id text,
  -- מתי נרשם ה-watch בפועל. ⚠️ הוא פג אחרי 7 ימים, וללא חידוש הסנכרון
  -- נדם בשקט בדיוק שבוע אחרי ההפעלה — בלי שגיאה ובלי סימן.
  add column if not exists watch_started_at timestamptz;
