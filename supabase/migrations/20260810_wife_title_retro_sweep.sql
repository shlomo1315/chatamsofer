-- סריקה חוזרת: תואר האישה "והרבנית" → "ומרת".
--
-- ⚠️ למה שוב, אחרי 20260805 שכבר המירה את כל העץ:
-- normalizeLineageNodeName מחזיר שם שכבר מנוסח ("רבי ...") *מילה במילה*, בלי
-- להרכיב אותו מחדש. שם כזה מגיע מטופס נדרים פלוס ומייבוא חוזר, ולכן "והרבנית"
-- המשיך להיכנס לעץ גם אחרי ההמרה — ואותו אדם הופיע בשני ניסוחים, שנראים
-- למנגנון המיזוג כשני אנשים.
--
-- הקוד תוקן (normalizeWifeTitle), וכאן מנקים את מה שהספיק להיכנס בינתיים.
--
-- ⚠️ ההחלפה דורשת רווחים משני הצדדים ואת ו' החיבור — כדי לא לפגוע בשם שמתחיל
-- ב"הרבנית" או בשם משפחה שמכיל את המילה. אידמפוטנטי: הרצה חוזרת אינה משנה דבר.
update public.lineage_nodes
set name = replace(name, ' והרבנית ', ' ומרת ')
where name like '% והרבנית %';

-- שרשרת הייחוס השמורה בכרטסת מחזיקה עותק של שמות הצמתים. אם היא נשארת עם
-- הניסוח הישן, ההשוואה בין "מקומו של הנרשם בשרשרת" לבין שם הצומת בעץ נכשלת,
-- וההשלמה למפרע רואה נרשם קיים כאילו אין לו צומת.
update public.beneficiaries
set lineage_chain = replace(lineage_chain::text, ' והרבנית ', ' ומרת ')::jsonb
where lineage_chain::text like '% והרבנית %';
