-- ─────────────────────────────────────────────────────────────────────────────
-- אימות מייל שאינו חובה — מעקב אחר מי אימת ומי לא.
--
-- עד כה אימות המייל היה חובה ברישום בפורטל, ולכן לא היה צורך לתעד אותו:
-- כל מי שנרשם — אימת. משנוסף מתג בהגדרות שמאפשר לכבות את הדרישה, נוצר פער
-- בין מוטב שאימת למוטב שלא, ובלי תיעוד אין דרך לדעת את מי לבקש לאמת בהמשך.
--
-- email_verified_at — מועד האימות. NULL = טרם אומת.
-- ─────────────────────────────────────────────────────────────────────────────

alter table beneficiaries add column if not exists email_verified_at timestamptz;

comment on column beneficiaries.email_verified_at is
  'מועד אימות כתובת המייל בקוד חד-פעמי. NULL = טרם אומת.';

-- ⚠️ מילוי למפרע: כל מוטב קיים שיש לו מייל מסומן כמאומת.
--
-- זו הנחה מכוונת ולא דיוק היסטורי. הרישום בפורטל דרש אימות מייל עד היום,
-- ולכן לרובם המוחלט זה נכון. עבור המיעוט שנרשם דרך נדרים (שם האימות מעולם
-- לא נדרש) זה אינו מדויק — אבל החלופה גרועה בהרבה: לסמן אלפי מוטבים ותיקים
-- כ"טרם אומת" פירושו לבקש מכולם לאמת מייל שכבר עובד, על לא עוול בכפם.
--
-- החיתוך נקבע כאן: מהמיגרציה ואילך התיעוד אמיתי, ונשלט ע"י המתג בהגדרות.
update beneficiaries
   set email_verified_at = coalesce(created_at, now())
 where email is not null
   and btrim(email) <> ''
   and email_verified_at is null;

-- אחזור מהיר של "מי טרם אימת" למסך ניהול / דוח
create index if not exists beneficiaries_email_unverified_idx
    on beneficiaries (email_verified_at)
 where email_verified_at is null;
