-- ת"ז על צומת בעץ הדורות.
--
-- הרקע: כשמשפחה מאושרת, הילדים שהיא הזינה (עם ת"ז) נכנסים לעץ כצמתים מאושרים
-- מיד — כדי שלא יהיה צורך לאשר כל אחד מהם שוב כשיבוא להירשם, וכדי שהוא ימצא
-- את עצמו ברשימת הבחירה במקום ליצור לעצמו רשומה כפולה.
--
-- הת"ז נשמרת על הצומת בדיוק בשביל זה: היא המפתח היציב שמונע יצירה כפולה של
-- אותו ילד באישור חוזר של המשפחה (השם עשוי להשתנות — ניסוח, תואר, שם נישואין),
-- ומאפשרת לזהות בהמשך שהנרשם החדש הוא בדיוק אותו צומת.
--
-- ריק ברוב הצמתים — הדורות ההיסטוריים אינם בעלי ת"ז.
-- ─────────────────────────────────────────────────────────────────────────────

alter table public.lineage_nodes
  add column if not exists id_number text;

create index if not exists lineage_nodes_id_number_idx
  on public.lineage_nodes(id_number)
  where id_number is not null;
