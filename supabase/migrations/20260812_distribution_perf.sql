-- מסך החלוקה נטען לאט — האינדקסים שחסרו.
--
-- מה קרה: המסך שולף את כל הנרשמים של חלוקה אחת, ממוין לפי מועד הרישום
-- יורד. היה אינדקס על distribution_id (כלומר *הסינון* היה מהיר), אבל לא היה
-- שום אינדקס שמכסה גם את המיון — ולכן Postgres שלף את כל שורות החלוקה
-- ומיין אותן מחדש בכל טעינה של הדף.
--
-- ⚠️ ככל שנרשמים יותר, כך זה מחמיר: המיון גדל עם מספר הנרשמים, בדיוק בתקופה
-- שבה המסך נטען הכי הרבה (ימי הרישום עצמם).
-- ═══════════════════════════════════════════════════════════════════════════

-- 🔴 האינדקס המרכזי: סינון לפי חלוקה *וגם* מיון לפי מועד רישום יורד, באותו
-- סדר שבו השאילתה מבקשת אותם. עכשיו Postgres קורא את השורות כשהן כבר
-- ממוינות, במקום למיין הכול מחדש.
create index if not exists distribution_recipients_dist_registered_idx
  on public.distribution_recipients (distribution_id, registered_at desc);

-- ⚠️ הצטרפות הנרשמים לטבלת המוטבים היא ה-join היחיד בשאילתה. בלי אינדקס על
-- המפתח הראשי בצד המוטבים היא נעשית שורה-אחר-שורה.
-- (beneficiaries.id הוא PK ולכן מאונדקס — כאן רק מוודאים שהכיוון ההפוך קיים.)
create index if not exists distribution_recipients_ben_dist_idx
  on public.distribution_recipients (beneficiary_id, distribution_id);

-- מסך צפיפות: ספירת הנרשמים לכל חלוקה במסך הרשימה.
-- ⚠️ אינדקס חלקי לא יעזור כאן — הספירה היא על כל השורות.
analyze public.distribution_recipients;
