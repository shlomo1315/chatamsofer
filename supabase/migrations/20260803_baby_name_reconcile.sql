-- ─────────────────────────────────────────────────────────────────────────────
-- יישור שם התינוק בין שני המקומות שבהם הוא נשמר.
--
-- הרקע: שם התינוק נשמר גם בשדה `baby_name` וגם בתוך המערך `babies` (שנכתב בכל
-- בקשת לידה, גם ללידה בודדת), ואף כותב לא סנכרן ביניהם. הקוראים התפצלו — כרטסת
-- הלידה מציגה את המערך, והרשימה/בית ההחלמה/הכרטיסים/הדוחות מציגים את השדה —
-- ולכן אותה יולדת נראתה במקביל כ"עדיין אין שם" בכרטסת וכשם ישן במסך הראשי,
-- והשם הישן הוא שנשלח לבית ההחלמה (אייזנער חוה רחל).
--
-- הקוד תוקן (lib/babyNames — קריאה וכתיבה דרך מקור אחד). כאן מיושרות הרשומות
-- הקיימות, ורק במקרים שאין בהם ספק:
--
--  1. הדגל "עדיין אין שם" דלוק ובמערך אין שם → השדה הסקלרי מתרוקן. זה המצב של
--     היולדת שדיווחה: היא ציינה שאין שם, והטקסט הישן נשאר בשדה והמשיך להישלח.
--  2. הדגל כבוי, השדה הסקלרי ריק ובמערך יש שם → השם מושלם לשדה, כדי שהמסכים
--     שקוראים אותו יציגו את מה שבאמת יש.
--
-- ⚠️ מה שלא נעשה כאן: לא נוגעים ברשומה שיש בה שם בשני המקומות (גם אם שונה) ולא
-- מכבים דגלים לפי ניחוש — הכרעה בין שני שמות היא של הצוות, לא של מיגרציה.
-- ─────────────────────────────────────────────────────────────────────────────

-- 1) "עדיין אין שם" — ניקוי הטקסט הישן שנשאר בשדה
update public.maternity_aids
   set baby_name = null,
       updated_at = now()
 where coalesce(baby_name_pending, false) = true
   and baby_name is not null
   and (
     jsonb_typeof(babies) <> 'array'
     or jsonb_array_length(babies) = 0
     or nullif(btrim(coalesce(babies -> 0 ->> 'name', '')), '') is null
   );

-- 2) שם קיים במערך אך חסר בשדה הסקלרי — השלמה
update public.maternity_aids
   set baby_name = nullif(btrim(babies -> 0 ->> 'name'), ''),
       updated_at = now()
 where coalesce(baby_name_pending, false) = false
   and nullif(btrim(coalesce(baby_name, '')), '') is null
   and jsonb_typeof(babies) = 'array'
   and jsonb_array_length(babies) > 0
   and nullif(btrim(coalesce(babies -> 0 ->> 'name', '')), '') is not null;
