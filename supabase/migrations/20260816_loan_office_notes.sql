-- ─────────────────────────────────────────────────────────────────────────────
-- הערות המשרד על בקשת ההלוואה — שדה פנימי לשימוש הצוות.
--
-- ⚠️ עמודה נפרדת מ-notes ולא שימוש חוזר בה: notes הוא *הערות המבקש*,
-- ממולא בטופס ההגשה ומוצג בכרטסת כדברי הפונה. ערבוב שתי הכתיבות באותו
-- שדה היה מאפשר למשרד לדרוס את מה שהמבקש כתב, ומוחק את ההבחנה בין
-- "מה הוא ביקש" לבין "מה אנחנו חושבים על זה".
--
-- ⚠️ פנימי בלבד — אינו נשלח למבקש ואינו מופיע במיילים.
--
-- ⚠️ nullable ללא ברירת מחדל: בקשות קיימות פשוט חסרות הערות.
-- ─────────────────────────────────────────────────────────────────────────────

alter table public.loans
  add column if not exists office_notes text;

comment on column public.loans.office_notes is
  'הערות פנימיות של המשרד על הבקשה. אינן נחשפות למבקש. נפרד מ-notes שהוא הערות המבקש.';
