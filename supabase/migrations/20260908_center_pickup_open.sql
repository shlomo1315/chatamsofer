-- ─────────────────────────────────────────────────────────────────────────────
-- פתיחת חלוקת הכרטיסים לכל מוקד בנפרד.
--
-- 🔴 הבעיה: pickup_open הוא מתג יחיד לכל החלוקה. המוקדים אינם מחלקים
-- באותו יום — מוקד שקיבל את הכרטיסים מחלק כבר היום, ואחר יקבל בעוד יומיים.
-- מתג אחד מכריח לבחור בין "כולם מחכים לאחרון" לבין "מי שאין לו כרטיס ביד
-- מתבקש להקיש מספר שאין לו".
--
-- ⚠️ העמודה נוספת ל-holiday_center_openings ואינה טבלה חדשה: הטבלה כבר
-- מחזיקה את הקשר חלוקה↔מוקד. אבל היא עונה עד כה על שאלה *אחרת* — אילו
-- מוקדים מוצעים לבחירה. השאלה החדשה היא אילו מוקדים כבר חילקו בפועל,
-- ולכן היא עמודה נפרדת ולא שינוי משמעות של הקיים.
--
-- 🔴 אין למחוק שורות מהטבלה כדי "לסגור" מוקד לשיוך: השורות האלה הן
-- הרשימה שעל בסיסה 6,109 משפחות כבר בחרו מוקד, ומחיקתן הייתה מוחקת
-- בחירות קיימות. NULL בעמודה הזו = נבחר אך טרם מחלק.
--
-- NULL  = המוקד טרם החל בחלוקת הכרטיסים (ברירת המחדל — שום מוקד לא נפתח
--         מאליו בעקבות המיגרציה).
-- תאריך = המוקד פתוח לשיוך כרטיסים, ומאז מתי.
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE holiday_center_openings
  ADD COLUMN IF NOT EXISTS pickup_open_at timestamptz;

COMMENT ON COLUMN holiday_center_openings.pickup_open_at IS
  'מתי המוקד החל לחלק כרטיסים. NULL = טרם החל, ואי אפשר לשייך כרטיס דרכו. '
  'נשלט יחד עם distributions.pickup_open — המתג הראשי גובר.';

-- ⚠️ אינדקס חלקי: השאילתה בשלוחה שואלת תמיד "האם המוקד הזה פתוח",
-- והיא רצה בכל שיחה נכנסת.
CREATE INDEX IF NOT EXISTS idx_center_openings_pickup
  ON holiday_center_openings (distribution_id, center_id)
  WHERE pickup_open_at IS NOT NULL;
