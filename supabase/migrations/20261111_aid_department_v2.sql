-- מחלקת סיוע לפי העיצוב המאושר: מספר בקשה רץ, פרטי משפחה והכנסות, סיבות נוספות,
-- הערה למגיש ותזכורת למנהל. הקוד עובד גם לפני שהמיגרציה רצה.
alter table public.financial_aid_requests drop constraint if exists financial_aid_requests_aid_type_check;
alter table public.financial_aid_requests add constraint financial_aid_requests_aid_type_check
  check (aid_type in ('medical','widow','orphans','econ','other'));

alter table public.financial_aid_requests
  add column if not exists request_no bigint generated by default as identity (start with 1001),
  add column if not exists family jsonb,
  add column if not exists income jsonb,
  add column if not exists decision_note text,
  add column if not exists reminder_sent_at timestamptz;

create unique index if not exists financial_aid_requests_request_no_key on public.financial_aid_requests (request_no);

alter table public.financial_aid_documents add column if not exists label text;
alter table public.financial_aid_documents drop constraint if exists financial_aid_documents_kind_check;
alter table public.financial_aid_documents add constraint financial_aid_documents_kind_check
  check (kind in ('id_card','medical','other'));
