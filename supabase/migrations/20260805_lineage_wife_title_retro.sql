-- עדכון רטרו: ניסוח האישה בעץ הדורות שונה מ-"הרבנית" ל-"מרת".
-- הפורמט: «רבי <בעל> והרבנית <אישה> <משפחה>» → «רבי <בעל> ומרת <אישה> <משפחה>».
--
-- ⚠️ מחליפים רק את הצירוף " והרבנית " (עם רווחים סביב) — כדי לא לפגוע בשם
-- שמתחיל ב"הרבנית" או במקרים אחרים. ההחלפה גלובלית בשם (replace, לא regex).
-- בטוח: משפיע רק על שורות שמכילות בדיוק את הצירוף הזה.
update public.lineage_nodes
set name = replace(name, ' והרבנית ', ' ומרת ')
where name like '% והרבנית %';
