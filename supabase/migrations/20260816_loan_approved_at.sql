-- ─────────────────────────────────────────────────────────────────────────────
-- מועד אישור ההלוואה ומי אישר.
--
-- ⚠️ rejected_at כבר קיים (20260813_loan_rejection) אבל approved_at לא —
-- כלומר ניתן היה לומר מתי בקשה נדחתה, אך לא מתי אושרה. כרטסת ההלוואה
-- מציגה עכשיו את ההחלטה שהתקבלה עם מועדה, ובלי העמודה הזו האישור היה
-- מוצג בלי תאריך.
--
-- ⚠️ nullable ללא ברירת מחדל: בקשות שאושרו לפני השדה אינן יודעות מתי,
-- וקביעת now() עבורן הייתה ממציאה תאריך שגוי לכל ההיסטוריה.
-- ─────────────────────────────────────────────────────────────────────────────

alter table public.loans
  add column if not exists approved_at timestamptz;

comment on column public.loans.approved_at is
  'מועד אישור הבקשה. null = אושרה לפני הוספת השדה, או טרם אושרה.';
