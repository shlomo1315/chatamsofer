-- קישור תיקון השם ליולדת אינו דורש שדה DB: הוא טוקן HMAC חתום (lib/publicToken, kind='n',
--   תקף 7 ימים) — stateless, ולכן אין כאן עמודות token.
-- ─────────────────────────────────────────────────────────────────────────────

alter table public.maternity_aids
  add column if not exists baby_name_pending boolean not null default false;
