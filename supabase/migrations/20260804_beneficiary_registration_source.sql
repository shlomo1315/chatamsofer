-- ערוץ ההרשמה של הצאצא — באיזה אופן הוא נרשם לאיגוד.
--
-- עד כה זה לא נשמר בשום מקום: אותה כרטסת יכולה להגיע מהאתר, מטופס נדרים פלוס,
-- מהמייל או מהזנה ידנית במשרד, ואחרי השמירה לא היה שום סימן מאיפה. זה נתון
-- תפעולי — לפיו יודעים איזה ערוץ עובד, למי לפנות ואיך, ומה לבדוק כשמשהו חסר.
--
-- ⚠️ nullable ובלי ברירת מחדל, ובכוונה: רשומות שנרשמו לפני העמודה הזו יוצגו
-- כ"לא תועד" ולא ישויכו לערוץ בניחוש. השלמה בדיעבד ל'portal' הייתה נראית
-- כנתון אמיתי, ואי אפשר להבדיל בין רשומה מהאתר לרשומה מנדרים בדיעבד.
-- ─────────────────────────────────────────────────────────────────────────────

alter table public.beneficiaries
  -- portal | nedarim | email | phone | admin (זהה לערוצי הרישום בחלוקות)
  add column if not exists registration_source text;

-- פילוח "כמה נרשמו מכל ערוץ" נעשה על כל המאגר
create index if not exists beneficiaries_registration_source_idx
  on public.beneficiaries(registration_source);
