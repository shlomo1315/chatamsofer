-- חלוקות חגים — מתג פעילה / מושבתת לכל חלוקה.
--
-- חלוקה מושבתת (enabled=false) אינה עובדת בשום ערוץ: הטלפון, הפורטל, המייל
-- וטופס נדרים מתנהגים כאילו אינה קיימת, ופעולות הניהול (טעינה, שוברים, שיוך,
-- הודעות) נחסמות. זה נפרד מ-registration_open ומ-status, ואינו משנה אותם.
--
-- ⚠️ ברירת המחדל פעילה, כדי שחלוקות קיימות ימשיכו לעבוד בדיוק כמו קודם.
-- בטוחה להרצה חוזרת.

alter table public.distributions
  add column if not exists enabled boolean not null default true;
