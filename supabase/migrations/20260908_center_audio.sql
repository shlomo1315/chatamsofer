--
-- 🔴 שם הקובץ כולל חותמת זמן. ימות ממטמנת לפי שם הקובץ, ושם קבוע היה
-- משמיע את ההקלטה הישנה לנצח בלי שום סימן שמשהו לא עודכן.
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE holiday_centers
  ADD COLUMN IF NOT EXISTS audio_file text;

COMMENT ON COLUMN holiday_centers.audio_file IS
  'שם קובץ ההקלטה בשלוחת החגים בימות (בלי סיומת), להשמעת פרטי המוקד בקול אנושי. NULL = ייקרא ב-TTS מהשדות. השם כולל חותמת זמן — ימות ממטמנת לפי שם הקובץ.';
