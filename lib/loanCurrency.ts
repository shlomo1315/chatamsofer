// ─────────────────────────────────────────────────────────────────────────────
// פורמט סכום הלוואה — מקור אמת יחיד.
//
// 🔴 ההלוואות נקובות בדולר. הסכום מוקלד בדולרים (תקרת הבקשה 10,000$),
// וההחזר מתבצע בשקלים לפי שער היום.
//
// ⚠️ אישורי הגמ"ח שנשלחו למשפחות הציגו "₪" על אותם מספרים — כלומר הצהירו
// סכום שאינו קיים, לא מה שהמשפחה ביקשה ולא מה שתקבל. הפורמט שוכפל בכל
// מסך ומייל בנפרד, ולכן תיקון במקום אחד לא הגיע לשאר.
//
// 🔴 להלוואות בלבד. סיוע רפואי, חלוקות חגים ועזר ליולדות *כן* בשקלים —
// החלת הפונקציה הזו עליהם תשקר באותה מידה, רק בכיוון ההפוך.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * סכום הלוואה לתצוגה: `$5,000`.
 *
 * ⚠️ הסימן לפני המספר, בשונה מהשקל — כך זה בכל מסכי ההלוואות.
 * ⚠️ מפריד אלפים באנגלית (en-US): he-IL מוסיף תווי כיווניות שנשברים
 * במייל ובאקסל, והמספר נראה הפוך.
 * ⚠️ null/undefined מחזירים מחרוזת ריקה ולא "$0": שדה שטרם אושר אינו
 * הלוואה על סכום אפס.
 */
export function fmtLoanAmount(n?: number | null): string {
  if (n == null) return ''
  const v = Math.round(Number(n) || 0)
  return `$${v.toLocaleString('en-US')}`
}
