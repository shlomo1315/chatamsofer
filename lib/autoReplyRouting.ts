/** תיבות שיש להן מענה אוטומטי משלהן, ולכן אינן מקבלות את הגנרי. */
export const DEDICATED_REPLY_DEPARTMENTS = ['igud', 'gemach'] as const

export function shouldSendGenericReply(department: string | null | undefined): boolean {
  if (!department) return true
  return !(DEDICATED_REPLY_DEPARTMENTS as readonly string[]).includes(department)
}
