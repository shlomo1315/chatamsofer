// חילוץ סכום כספי מתשובת נדרים פלוס.
//
// 🔴 נדרים מחזירה סכומים כמחרוזות, לעתים עם סימן מטבע או רווחים
// ("0.21", "600", "12.50 ₪"). הפירוק היה כתוב בשורה אחת בתוך הראוט,
// ושם נפלה שגיאת מחלקה: `[^d.-]` במקום `[^\d.-]` — בלי לוכסן, המחלקה
// מוחקת את **הספרות** ומשאירה את האות d.
//
// ⚠️ התוצאה: "600" הפך למחרוזת ריקה, "0.21" ל-".21", והעמודה "כסף
// שחזר לארנק" נשארה ריקה ב-30 מתוך 36 פריקות — כולל פריקות של היום.
// זה נראה כנתונים היסטוריים חסרים, בזמן שזה היה תו אחד.
//
// ⚠️ מרוכז כאן ולא משוכפל: זו הנקודה היחידה שממירה סכום מנדרים, וכל
// עותק שני היה נשאר עם הבאג.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * הסכום כמספר, או null אם אין נתון.
 *
 * 🔴 null ולא 0 כשאין ערך: אפס פירושו "לא חזר כלום" — נתון אמיתי על
 * כרטיס שנוצל במלואו. החזרת 0 על חוסר מידע הייתה מוחקת את ההבחנה.
 */
export function parseNedarimAmount(raw: unknown): number | null {
  if (typeof raw === 'number') return Number.isFinite(raw) ? Math.abs(raw) : null
  const s = String(raw ?? '').trim()
  if (!s) return null

  // ⚠️ \d עם לוכסן — זה בדיוק התו שנפל.
  const cleaned = s.replace(/[^\d.-]/g, '')
  if (!cleaned || !/\d/.test(cleaned)) return null

  const n = Number(cleaned)
  if (!Number.isFinite(n)) return null
  // ⚠️ ערך מוחלט: נדרים מסמנת פריקה כשלילית, ו"חזר לארנק" חיובי תמיד.
  return Math.abs(n)
}
