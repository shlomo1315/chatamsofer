// ─────────────────────────────────────────────────────────────────────────────
// מה נשמע במקש 2 — "לשמיעת המוקד שבחרתם".
//
// 🔴 השאלה שהמתקשר שואל היא "האם אני יכול לגשת לקחת את הכרטיס". התשובה
// נקבעת לפי pickup_open_at של המוקד שלו — בדיוק אותו שדה שמכריע במקש 3.
//
// ⚠️ הרקע: הבחירה נעשתה לפי load_status='loaded' בלבד. אבל הטעינה קורית
// רק *אחרי* שהמשפחה הגיעה למוקד והקישה את מספר הכרטיס, ולכן בכל הפרק
// שבין פתיחת המוקד לאיסוף בפועל נפלו כל המתקשרים ל-center_already —
// שנוסחו מסתיים ב"בזמן שהמוקדים ייפתחו תקבלו על כך עדכון מסודר".
// המשפחה שמעה שעליה להמתין להודעה שכבר קיבלה, על מוקד שכבר מחלק.
//
// ⚠️ שני המסלולים חייבים לענות אותו דבר על אותה שאלה: מוקד שמקש 3 מוכן
// לקבל ממנו מספר כרטיס אינו יכול להיות מוקד שמקש 2 אומר עליו שטרם נפתח.
// ─────────────────────────────────────────────────────────────────────────────

export interface CenterStatusInput {
  /** האם *המוקד של המשפחה* כבר החל לחלק (holiday_center_openings.pickup_open_at). */
  centerPickupOpen: boolean
  /** האם הכרטיס כבר הוטען בפועל (load_status='loaded'). */
  loaded: boolean
}

/**
 * מפתח ההודעה שתושמע במקש 2.
 *
 * ⚠️ הטעינה גוברת על הדגל: כרטיס שהוטען ידנית מהמשרד לפני שהמוקד נפתח
 * רשמית כבר נמצא ביד המשפחה, ואין לה על מה להמתין.
 */
export function centerStatusKey(o: CenterStatusInput): 'card_ready' | 'center_already' {
  if (o.loaded) return 'card_ready'
  return o.centerPickupOpen ? 'card_ready' : 'center_already'
}
