// 🔴 מה שקרה בפרודקשן: כתובת השיבה על הודעת "הבקשה לא נקלטה" שלנו.
// התשובה נקלטה כפנייה חדשה, לא הייתה בה ת"ז בנושא (רק "Re: בקשת לידה
// לא נקלטה"), ולכן יצאה דחייה נוספת — שעליה היא השיבה שוב. ביומן הנכנס
// נספרו ארבעה סיבובים על אותה כותרת, בתוך רבע שעה.
//
// ⚠️ הזיהוי צר בכוונה: *קידומת תשובה* + *הנושא שאנחנו מייצרים*. "Re:"
// לבדו אינו מספיק — אדם שמשיב על התכתבות קודמת עם המזכירות שולח פנייה
// לגיטימית, ובליעתה הייתה משתיקה בקשה אמיתית בלי שאיש יידע.
// ─────────────────────────────────────────────────────────────────────────────

/** קידומות תשובה/העברה, בעברית ובאנגלית. Gmail מקנן אותן בכל סבב. */
const REPLY_PREFIX = /^\s*((re|fwd|fw|השב|העבר)\s*:\s*)+/i

/**
 * הביטוי שמופיע בנושא של הודעת הדחייה שלנו.
 *
 * ⚠️ נגזר מ-emailIntakeRejectedEmail: `${typeLabel} לא נקלטה — היכל החתם סופר`.
 * שינוי הנוסח שם מחייב עדכון כאן — ולכן הביטוי רחב (סוג הבקשה משתנה)
 * ותופס את החלק הקבוע בלבד.
 */
const OUR_REJECTION = /לא נקלטה/

/**
 * האם המייל הנכנס הוא תשובה על הודעת דחייה שאנחנו שלחנו.
 *
 * 🔴 שני התנאים נדרשים יחד. בלי הקידומת זו שאלה לגיטימית ("למה הבקשה
 * לא נקלטה?"), ובלי הביטוי זו תשובה על התכתבות אחרת לגמרי.
 */
export function isReplyToOurMail(subject: string | null | undefined): boolean {
  const s = String(subject ?? '').trim()
  if (!s) return false
  if (!REPLY_PREFIX.test(s)) return false
  return OUR_REJECTION.test(s.replace(REPLY_PREFIX, ''))
}
