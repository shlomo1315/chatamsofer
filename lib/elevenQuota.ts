// תרגום שגיאות ElevenLabs להודעה שאפשר לפעול לפיה.
//
// 🔴 מכסה שנגמרה נראתה כתקלה במערכת: הכפתור "יצירת קול" נלחץ, לא קרה
// דבר, וההודעה נשארה "קול ממוחשב". השגיאה כן הוחזרה — אבל כ-JSON גולמי
// באנגלית, שלא נקרא כמשפט ולא נקשר למכסה. התוצאה היא חיפוש באג בקוד
// במקום טעינת קרדיטים.
//
// ⚠️ ההודעה חייבת לומר *מה לעשות*: "נגמרה המכסה" היא פעולה, "ElevenLabs
// החזיר שגיאה: {detail:{status:..." אינה.
// ─────────────────────────────────────────────────────────────────────────────

/** ניסוחי המכסה של ElevenLabs — הם משתנים בין גרסאות, ולכן זיהוי רחב. */
const QUOTA_RE = /quota_exceeded|exceeds your quota|quota|credits remaining|too_many_requests|rate.?limit/i
const KEY_RE = /invalid_api_key|invalid api key|unauthorized|missing_api_key/i

/**
 * הודעת שגיאה בעברית לכשל ביצירת קול.
 *
 * @param status קוד ה-HTTP שהוחזר (0 = כשל רשת)
 * @param errText גוף התשובה כפי שהתקבל
 */
export function describeElevenError(status: number, errText: string): string {
  const raw = String(errText ?? '').trim()

  // ⚠️ המפתח נבדק לפני המכסה: 401 עשוי להחזיר את שניהם, והפעולה שונה
  // לגמרי — טעינת קרדיטים לא תעזור למפתח שפג.
  if (KEY_RE.test(raw)) {
    return 'מפתח ה-API של ElevenLabs אינו תקין או פג — יש לעדכן אותו בהגדרות'
  }

  if (QUOTA_RE.test(raw) || status === 429) {
    return 'נגמרה מכסת ההמרות ב-ElevenLabs — יש לטעון קרדיטים בחשבון, '
      + 'ועד אז ההודעה תושמע בקול הממוחשב של ימות'
  }

  if (status === 0) {
    return `לא הייתה תשובה מ-ElevenLabs${raw ? ` (${raw})` : ''} — יש לנסות שוב`
  }

  // ⚠️ הטקסט המקורי נשמר: בליעתו מחזירה בדיוק למצב שבו הכפתור "לא עושה
  // כלום" בלי שום רמז מה נכשל.
  return `יצירת הקול נכשלה (${status || 'ללא קוד'})${raw ? `: ${raw}` : ''}`
}
