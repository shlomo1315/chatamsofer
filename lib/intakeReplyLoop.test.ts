import { describe, it, expect } from 'vitest'
import { isReplyToOurMail } from './intakeReplyLoop'

// ─────────────────────────────────────────────────────────────────────────────
// 🔴 לולאת דחיות — נצפתה בפרודקשן.
//
// כתובת השיבה על הודעת "הבקשה לא נקלטה" שלנו. התשובה נקלטה כפנייה חדשה,
// לא הייתה בה ת"ז בנושא (רק "Re: בקשת לידה לא נקלטה"), ולכן נשלחה דחייה
// נוספת — שעליה היא השיבה שוב. ביומן הנכנס נספרו ארבע סיבובים כאלה על
// אותה כותרת בדיוק, בתוך רבע שעה.
//
// ⚠️ הזיהוי הוא על *הנושא שלנו* ולא על "Re:" בכלל: אדם שמשיב על מייל
// אחר, או שולח "Re: בקשה ליולדת" ידנית, הוא פנייה לגיטימית שאסור לבלוע.
// ─────────────────────────────────────────────────────────────────────────────

describe('isReplyToOurMail — 🔴 הלולאה', () => {
  it('תשובה על הודעת הדחייה שלנו', () => {
    expect(isReplyToOurMail('Re: בקשת לידה לא נקלטה — היכל החתם סופר')).toBe(true)
  })

  it('העברה של אותה הודעה', () => {
    expect(isReplyToOurMail('Fwd: בקשת לידה לא נקלטה — היכל החתם סופר')).toBe(true)
  })

  it('⚠️ גם עם קידומות מקוננות — Gmail מוסיף שכבה בכל סבב', () => {
    expect(isReplyToOurMail('Re: Re: בקשת הלוואה לא נקלטה — היכל החתם סופר')).toBe(true)
  })

  it('קידומת באנגלית', () => {
    expect(isReplyToOurMail('RE: בקשת לידה לא נקלטה')).toBe(true)
  })
})

describe('isReplyToOurMail — ⚠️ פניות לגיטימיות אינן נבלעות', () => {
  it('🔴 "Re:" על נושא אחר — פנייה תקינה', () => {
    // אדם שמשיב על התכתבות קודמת עם המזכירות. בליעתו הייתה משתיקה
    // פנייה אמיתית בלי שאיש יידע.
    expect(isReplyToOurMail('Re: בקשה לבית החלמה')).toBe(false)
    expect(isReplyToOurMail('Re: 123456789')).toBe(false)
  })

  it('פנייה חדשה רגילה', () => {
    expect(isReplyToOurMail('בקשת לידה 123456789')).toBe(false)
  })

  it('נושא ריק אינו נחשב לולאה', () => {
    expect(isReplyToOurMail('')).toBe(false)
    expect(isReplyToOurMail(null)).toBe(false)
  })

  it('⚠️ הביטוי בגוף הנושא בלי קידומת — לא לולאה', () => {
    // מישהו שכותב מיוזמתו "למה הבקשה לא נקלטה?" — שאלה לגיטימית.
    expect(isReplyToOurMail('למה הבקשה לא נקלטה?')).toBe(false)
  })
})
