// ─────────────────────────────────────────────────────────────────────────────
// התווית של מספר הזיהוי — "ת.ז." או "דרכון".
//
// 🔴 231 מוטבים מזוהים בדרכון, והמסכים הציגו לכולם "ת.ז.". הנתון נשמר
// (id_doc_type / spouse_doc_type) ומעולם לא הוצג.
//
// ⚠️ זה לא ניסוח בלבד: משפחת לוק הגישה ארבע בקשות לידה על אותו תינוק
// והקלידה בכל פעם מספר אחר — פעמיים את מספרי ההורים עצמם — כי המסך
// ביקש "ת.ז." ממי שאין לו. אחת מהבקשות אושרה וכרטיס נטען.
//
// ⚠️ ברירת המחדל היא ת.ז.: רוב מוחלט מהמוטבים, וערך חסר אינו סיבה
// להציג "דרכון" על מי שאינו.
// ─────────────────────────────────────────────────────────────────────────────

export type IdDocType = 'id' | 'passport' | string | null | undefined

/** "ת.ז." או "דרכון" — לתווית שדה. */
export function idDocLabel(t: IdDocType): string {
  return t === 'passport' ? 'דרכון' : 'ת.ז.'
}

/** "תעודת זהות" או "דרכון" — לנוסח בתוך משפט. */
export function idDocLabelLong(t: IdDocType): string {
  return t === 'passport' ? 'דרכון' : 'תעודת זהות'
}
