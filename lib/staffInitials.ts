// ─────────────────────────────────────────────────────────────────────────────
// ראשי תיבות של שם המשתמש בהתכתבות פנימית — "משה כהן" → "מ.כ."
//
// 🔴 למה: בשרשור הבירור מול המבקש מופיע שם מלא של איש הצוות. ההתכתבות
// הזו נחשפת גם למבקש עצמו, ואין סיבה שהוא ידע מי בדיוק כתב לו.
//
// ⚠️ הכלל אחד לשני הפאנלים (הלוואות ויולדות). שני מימושים היו נסחפים,
// ואותו עובד היה מופיע אחרת בכל מסך.
//
// ⚠️ מה *לא* מקוצר, ולמה:
//   · שם יחיד ("מזכירות") — "מ." לבדה אינה מזהה איש. עדיף השם המלא.
//   · תווית מערכת ("צוות הגמ״ח", "המזכירות") — אלה אינם שמות אנשים.
//   · שם ריק — מוחזרת ברירת המחדל של הקורא.
// ─────────────────────────────────────────────────────────────────────────────

/** מילים שאינן חלק מהשם ואינן נספרות כראש תיבה. */
const PARTICLES = new Set(['בן', 'בת', 'בר', 'אבן', 'אל', 'דה', 'די', 'ה', 'ו'])

/**
 * ראשי תיבות מתוך שם מלא.
 *
 * "משה כהן"        → "מ.כ."
 * "שרה לאה פרידמן" → "ש.ל.פ."
 * "מזכירות"        → "מזכירות"  (שם יחיד — לא מקוצר)
 */
export function toInitials(name?: string | null): string {
  const raw = String(name ?? '').trim()
  if (!raw) return ''

  // ⚠️ פיצול גם על מקף: "בת-שבע" הם שני חלקים של שם אחד, אבל
  // "כהן-לוי" הוא שם משפחה כפול. שניהם מקוצרים באותה צורה.
  const parts = raw
    .split(/[\s\-־]+/)
    .map(p => p.replace(/["'׳״.]/g, '').trim())
    .filter(p => p.length > 0 && !PARTICLES.has(p))

  // ⚠️ שם יחיד אינו מקוצר: "מ." לבדה אינה מזהה איש, והקיצור רק מוחק
  // מידע בלי להסתיר דבר.
  if (parts.length < 2) return raw

  return parts.map(p => p[0] + '.').join('')
}

/**
 * מה שמוצג ליד הודעה של הצוות.
 *
 * ⚠️ תוויות מערכת אינן שמות של אנשים ואינן מקוצרות — "צוות הגמ״ח"
 * הוא כבר אנונימי, ו"צ.ה." רק היה מבלבל.
 */
const SYSTEM_LABELS = new Set(['צוות הגמ״ח', 'צוות הגמ"ח', 'המזכירות', 'מזכירות', 'הנהלה', 'המערכת'])

export function staffDisplayName(senderName?: string | null, fallback = 'המזכירות'): string {
  const raw = String(senderName ?? '').trim()
  if (!raw) return fallback
  if (SYSTEM_LABELS.has(raw)) return raw

  // 🔴 כתובת מייל אינה שם — ולא מוצגת ליולדת.
  //
  // ⚠️ למשתמש שאין לו שם מלא נשמר המייל ב-sender_name, והשרשור הציג
  // "5827799@gmail.com" לצד ההודעה. זו חשיפה של כתובת פרטית לפונה,
  // וגם אינה אומרת לו דבר.
  if (raw.includes('@')) return fallback

  return toInitials(raw)
}
