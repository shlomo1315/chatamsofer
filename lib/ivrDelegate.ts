// 🔴 עד כה ההעברה נעשתה ב-go_to_folder: ימות העבירה את השיחה לשלוחה
// אחרת, והמשכה כבר לא עבר דרכנו. המשמעות הייתה שכל שינוי בתפריט דרש
// נגיעה גם בהגדרות ימות, וכל שלוחה הייתה צריכה כתובת משלה.
//
// עכשיו הכל רץ תחת כתובת אחת, והשלוחה הראשית קוראת להנדלרים ישירות.
