// 🔴 ימות אינה שומרת מצב בין קריאות. המסלול הנוכחי מוחזר אליה כמשתנה
// וחוזר בקריאה הבאה — בלעדיו כל הקשה הייתה מתחילה מחדש מהתפריט, והמתקשר
// היה תקוע בלולאה בלי להבין למה.
//
// ⚠️ הכתובות הישנות ממשיכות לעבוד. מי שכבר הגדיר שלוחה נפרדת בימות אינו
// נשבר — הכתובת האחת היא תוספת, לא החלפה.
// ─────────────────────────────────────────────────────────────────────────────

/** שם המשתנה שבו נשמר המסלול. ⚠️ ייחודי — התנגשות עם משתנה קיים = לולאה. */
export const ROUTE_PARAM = 'ivr_route'

export type Route = 'holiday' | 'maternity'

const ROUTES: Record<string, Route> = { holiday: 'holiday', maternity: 'maternity' }

/** הקשה בתפריט הראשי → מסלול. ⚠️ 9 אינה כאן: היא הודעה שהתפריט משמיע בעצמו. */
const DIGIT_TO_ROUTE: Record<string, Route> = { '1': 'holiday', '2': 'maternity' }

/**
 * באיזה מסלול השיחה נמצאת.
 *
 * 🔴 המסלול השמור גובר על ההקשה: אחרי שנכנסו לחגים, הקשה "2" היא בחירה
 * *בתוך* החגים ולא מעבר ליולדות. בלי הקדימות הזו כל הקשה הייתה מקפיצה
 * את המתקשר בין מסלולים.
 */
export function resolveRoute(params: Record<string, string>, digit: string): Route | null {
  const saved = String(params[ROUTE_PARAM] ?? '').trim()
  // ⚠️ מסלול לא מוכר נזרק ולא מועבר הלאה: ערך זר (או ישן, מגרסה קודמת)
  // היה מגיע להנדלר שאינו יודע לטפל בו.
  if (saved && ROUTES[saved]) return ROUTES[saved]

  const d = String(digit ?? '').trim()
  return DIGIT_TO_ROUTE[d] ?? null
}
