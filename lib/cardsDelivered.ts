// ─────────────────────────────────────────────────────────────────────────────
// "נמסרו" — כרטיסים שיצאו מהמגירה ואינם חוזרים.
//
// ⚠️ זהות חשבונאית ולא ספירת תיקים: נקנו פחות מה שנשאר במלאי.
//
// למה לא לספור לידות: הדשבורד ספר תיקים עם status='active' והציג 146,
// בעוד שנקנו 300 והמלאי 148 — כלומר 294, ושישה כרטיסים "נעלמו". לידה
// שהושלמה קיבלה כרטיס שיצא מהמגירה ואינו חוזר, אבל היא כבר אינה active
// ולכן נשמטה מהספירה. אותה משפחת באגים של "נקנו": ספירת מצב *עכשווי*
// כתשובה לשאלה *מצטברת*.
//
// ⚠️ הצורה הזו גם מונעת את הפער בין המסכים: מסך הכרטיסים והדשבורד גוזרים
// את המספר מאותם שני נתונים, ולא יכולים להיפרד זה מזה.
//
// מחזיר null — ולא 0 — כשאין נתון או כשהמספרים אינם עקביים. המסך מציג
// אז '—'. מספר שגוי גרוע ממקף: אי אפשר להבחין בו.
// ─────────────────────────────────────────────────────────────────────────────
export function cardsDelivered(totalPurchased: number, balance: number): number | null {
  if (!Number.isFinite(totalPurchased) || !Number.isFinite(balance)) return null
  if (totalPurchased <= 0) return null      // טרם נרשמו רכישות
  if (balance > totalPurchased) return null // מלאי גדול מהרכישות — נתון חסר, לא עובדה
  return totalPurchased - balance
}
