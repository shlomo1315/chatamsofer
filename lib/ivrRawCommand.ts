// 🔴 לימות יש כ-40 סוגי שלוחות מתועדים (תא קולי, פקס, פילטר זמנים,
// זמני היום, ועידה, טריוויה ועוד). בניית כל אחד מהם בנפרד הייתה
// לוקחת שבועות, ורובם לעולם לא ישמשו כאן.
//
// ⚠️ במקום זה: המנהל מדביק את הפקודה מהתיעוד של ימות. כל סוג זמין
// מיד — כולל סוגים שימות תוסיף בעתיד, בלי שנשנה שורת קוד.
//
// 🔴 אבל פקודה חופשית שנכתבת ישירות לתשובה היא הזרקה. הפקודות מופרדות
// ב-"&", ולכן ערך אחד שמכיל "&" מוסיף פקודה שהמנהל לא התכוון אליה.
// שגיאה בתשובה אינה מפילה מסך — היא גורמת ל*כל* המתקשרים לשמוע
// שגיאה, והם פשוט מנתקים.
//
// ⚠️ הסינון הוא רשימת *היתר* צרה ולא רשימת חסימה: אי אפשר למנות מראש
// את כל הצורות השבורות, אבל אפשר למנות את הצורה התקינה היחידה —
// שם_פקודה=ערך, בלי מפריד ובלי שורה חדשה.
// ─────────────────────────────────────────────────────────────────────────────

export const RAW_COMMAND_HINT =
  'הדביקו כאן פקודה מהתיעוד של ימות — למשל go_to_folder=/7 לתא קולי. ' +
  'כך אפשר להשתמש בכל סוג שלוחה שימות מציעה, גם כזה שאין לו כפתור כאן.'

/** ⚠️ פקודה אמיתית קצרה. אלפי תווים = טעות או הדבקה שגויה. */
const MAX_LEN = 1000

/**
 * מחזירה את הפקודה אם היא בטוחה לשליחה, אחרת null.
 *
 * 🔴 null ולא מחרוזת ריקה: מחרוזת ריקה שנכתבת לתשובה יוצרת פקודה
 * ריקה בין שני "&", ואין לדעת איך ימות מגיבה לה.
 */
export function sanitizeRawCommand(raw: string | null | undefined): string | null {
  const s = String(raw ?? '').trim()
  if (!s || s.length > MAX_LEN) return null

  // 🔴 "&" מפריד פקודות ו-"\n" שובר את גוף התשובה. שניהם הופכים
  // שדה אחד לשתי פקודות, וזו בדיוק ההזרקה.
  if (/[&\n\r]/.test(s)) return null

  // ⚠️ הצורה היחידה שמותרת: שם באותיות לטיניות/קו תחתון, סימן שווה,
  // וערך כלשהו. בלי סימן שווה זו אינה פקודה אלא טקסט.
  if (!/^[a-zA-Z_][a-zA-Z0-9_]*=.+$/.test(s)) return null

  return s
}
