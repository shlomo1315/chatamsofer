// ─────────────────────────────────────────────────────────────────────────────
// 🔴 join של Supabase מוחזר כמערך *או* כאובייקט.
//
// הצורה תלויה בסכימה ובנתיב השליפה, ואינה עקבית בין שאילתות. הסכנה היא
// שהטיפוס שמצהירים ידנית ("center?: { city: string }") אינו נכשל
// בקומפילציה כשהערך הוא מערך — הוא פשוט מחזיר undefined בזמן ריצה.
//
// כך בדיוק נעלמו מוקדי החלוקה מטבלת הנרשמים: המוקד נשמר במסד כראוי
// (center_id מלא, center_source='portal'), והטבלה הציגה "טרם נבחר".
// אין שגיאה, אין לוג — רק נתון שנראה חסר.
//
// ⚠️ להשתמש בכל מקום שקוראים join מקונן, גם כשנראה שהוא מחזיר אובייקט:
// "עובד אצלי" כאן הוא תלוי-שאילתה ולא ערובה.
// ─────────────────────────────────────────────────────────────────────────────

/** האיבר היחיד של join מקונן — בין אם הוחזר כמערך ובין כאובייקט. */
export function joinOne<T>(v: T | T[] | null | undefined): T | null {
  if (Array.isArray(v)) return v[0] ?? null
  return v ?? null
}
