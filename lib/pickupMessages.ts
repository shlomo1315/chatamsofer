// ─────────────────────────────────────────────────────────────────────────────
// ההודעה שהמשפחה מקבלת אחרי טעינת הכרטיס.
//
// 🔴 המטרה המוצהרת: **שאיש לא יגיע למוקד שלא בחר**. המוקד מקבל
// כרטיסים לפי מספר הנרשמים אליו, ומשפחה שמגיעה למוקד אחר לוקחת
// כרטיס של מישהו אחר — ומי שכן נרשם שם מגיע ולא מוצא.
//
// ⚠️ אין שוברים. ההודעה עצמה היא כל מה שהמשפחה מקבלת, ולכן היא חייבת
// לומר את הכול: איפה, ולמה רק שם.
//
// ⚠️ הניסוח מרתיע ואומר שהמערכת לא תאפשר להטעין כרטיס ממוקד אחר.
// בפועל **אין אכיפה טכנית** — זו החלטה מפורשת: הרתעה עדיפה על מנגנון
// שעלול לתקוע משפחה במוקד בגלל תקלה.
//
// 🔴 שלושת הערוצים אומרים את אותו הדבר. ניסוח שונה בין טלפון, מייל
// ואתר הוא בדיוק מה שגורם למשפחה לחשוב שהכלל אינו רציני.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * ליבת האזהרה — הרעיון שחוזר בכל הערוצים.
 *
 * ⚠️ בלי סימני פיסוק שה-TTS של ימות אינו סובל, כדי שאפשר יהיה
 * להשתמש בה גם בטלפון בלי עיבוד נוסף.
 */
export const PICKUP_WARNING_CORE =
  'שימו לב, ניתן לקבל את הכרטיס רק במוקד שבחרתם. ' +
  'כרטיס שיילקח ממוקד אחר לא ניתן יהיה להטעין'

/** ⚠️ ניקוי לתצוגה טלפונית — ראו ttsClean ב-lib/ivrRuntime. */
const forTts = (t: string) => t.replace(/[.\-"'&|׳״]/g, ' ').replace(/\s+/g, ' ').trim()

/**
 * הנוסח שמושמע בטלפון.
 *
 * ⚠️ שם מוקד ריק אינו משאיר "{center}" בהקראה: המשפט נבנה בלעדיו
 * ונשאר תקין, גם אם פחות מדויק.
 */
export function pickupPhoneText(centerLabel: string | null | undefined): string {
  const c = String(centerLabel ?? '').trim()
  const where = c
    ? `הכרטיס שלכם מוכן לאיסוף במוקד ${c}`
    : 'הכרטיס שלכם מוכן לאיסוף במוקד שבחרתם'
  return forTts(`${where}. ${PICKUP_WARNING_CORE}`)
}

/**
 * הנוסח שנשלח במייל.
 *
 * ⚠️ אינו מזכיר שובר — הוא בוטל. משפחה שתקרא "השובר מצורף" ולא תמצא
 * אותו תתקשר למשרד.
 *
 * ⚠️ אינו מבטיח תאריכים ושעות: מועדי החלוקה בכל מוקד טרם נקבעו,
 * והבטחה שתשתנה גרועה משתיקה.
 */
export function pickupEmailText(centerLabel: string | null | undefined): string {
  const c = String(centerLabel ?? '').trim()
  const where = c
    ? `הכרטיס שלכם מוכן לאיסוף במוקד ${c}.`
    : 'הכרטיס שלכם מוכן לאיסוף במוקד שבחרתם.'
  return [
    where,
    PICKUP_WARNING_CORE + '.',
    'בעזרת השם תישלח הודעה מסודרת לגבי הימים והשעות.',
  ].join('\n\n')
}

/** הנוסח שמוצג באתר. ⚠️ קצר — הוא מוצג לצד שם המוקד ממילא. */
export function pickupPortalText(centerLabel: string | null | undefined): string {
  const c = String(centerLabel ?? '').trim()
  const where = c
    ? `הכרטיס מוכן לאיסוף במוקד ${c}.`
    : 'הכרטיס מוכן לאיסוף במוקד שבחרתם.'
  return `${where} ${PICKUP_WARNING_CORE}.`
}
