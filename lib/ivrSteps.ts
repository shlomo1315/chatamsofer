// שרשרת השלבים של שלוחה — לתצוגה מקדימה על הכרטיס.
//
// ⚠️ רק המסלול הראשי (הילד הראשון בכל רמה) ולא כל הענפים: עץ החגים הוא
// שבע רמות עם הסתעפויות, והצגת כולן על הכרטיס הופכת את רשימת השלוחות
// לקיר טקסט שאי אפשר לסרוק במבט.
//
// המבנה המלא זמין בלשונית "מבנה השיחה" בתוך השלוחה.
// ─────────────────────────────────────────────────────────────────────────────

import type { IvrNode } from './ivrMap'

/**
 * כותרות השלבים לאורך המסלול הראשי.
 *
 * @param max מספר השלבים המרבי. ⚠️ ברירת המחדל 4 — מעבר לכך השרשרת
 *            נשברת לשורה שנייה ומאבדת את התועלת שלה כסריקה מהירה.
 */
export function mainPathTitles(tree: IvrNode[], max = 4): string[] {
  const out: string[] = []
  let current: IvrNode | undefined = tree[0]
  while (current && out.length < max) {
    out.push(current.title)
    current = current.children?.[0]
  }
  return out
}
