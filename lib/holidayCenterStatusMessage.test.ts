import { describe, it, expect } from 'vitest'
import { centerStatusKey } from './holidayCenterStatusMessage'

// ─────────────────────────────────────────────────────────────────────────────
// 🔴 מקש 2 ("לשמיעת המוקד שבחרתם") אמר למשפחות שהמוקד שלהן עוד ייפתח —
// בזמן שהוא כבר חילק כרטיסים.
//
// הבחירה בין ההודעות נעשתה לפי load_status='loaded' בלבד, כלומר לפי
// "האם הכרטיס כבר הוטען". בפועל הטעינה מתרחשת רק *אחרי* שהמשפחה מגיעה
// למוקד ומקישה את מספר הכרטיס — ולכן בכל התקופה שבין פתיחת המוקד לבין
// האיסוף בפועל, כל המתקשרים נפלו ל-center_already, שנוסחו מסתיים ב-
// "בזמן שהמוקדים ייפתחו תקבלו על כך עדכון מסודר".
//
// זו בדיוק ההודעה ההפוכה ממה שהמשפחה צריכה לשמוע: המוקד שלה פתוח, והיא
// התקשרה כדי לדעת לאן ללכת. 1,455 משפחות בארבעת מוקדי בני ברק שמעו
// שעליהן להמתין להודעה שכבר נשלחה.
//
// ⚠️ הקריטריון הנכון הוא pickup_open_at של המוקד — אותו שדה שמכריע
// במקש 3. שני המסלולים חייבים לענות אותו דבר על אותה שאלה.
// ─────────────────────────────────────────────────────────────────────────────

describe('🔴 מקש 2 — ההודעה נקבעת לפי פתיחת המוקד, לא לפי הטעינה', () => {
  it('המוקד פתוח והכרטיס טרם נאסף — אומר שהכרטיס ממתין, ולא "ייפתח בהמשך"', () => {
    expect(centerStatusKey({ centerPickupOpen: true, loaded: false })).toBe('card_ready')
  })

  it('המוקד טרם נפתח — נשאר "תקבלו עדכון מסודר"', () => {
    expect(centerStatusKey({ centerPickupOpen: false, loaded: false })).toBe('center_already')
  })

  it('הכרטיס כבר הוטען — ממשיך לומר שהוא מוכן', () => {
    expect(centerStatusKey({ centerPickupOpen: true, loaded: true })).toBe('card_ready')
  })

  // ⚠️ מצב אמיתי: כרטיס שהוטען ידנית מהמשרד לפני שהמוקד נפתח רשמית.
  // הטעינה היא עובדה חזקה יותר מהדגל — הכרטיס בידה, ואין מה להמתין לו.
  it('הוטען למרות שהמוקד סגור — הטעינה גוברת', () => {
    expect(centerStatusKey({ centerPickupOpen: false, loaded: true })).toBe('card_ready')
  })
})
