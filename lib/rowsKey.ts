const idOf = (r: unknown): string =>
  r && typeof r === 'object' && 'id' in r ? String((r as { id: unknown }).id) : ''

export function rowsKeyOf(all: readonly unknown[]): string {
  return `${all.length}:${idOf(all[0])}:${idOf(all[all.length - 1])}`
}
