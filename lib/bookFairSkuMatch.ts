// ─────────────────────────────────────────────────────────────────────────────
// התאמת מק"ט להקשה בטלפון.
//
// 🔴 למה זה קיים כמודול נפרד: הטלפון הוא הערוץ היחיד שבו המשתמש אינו
// רואה את מה שהקליד, ולכן מק"ט שלא נמצא נשמע לו כמו "הספר לא קיים".
// הלוגיקה כאן טהורה כדי שאפשר יהיה לבדוק *מה נמצא* בלי מסד.
//
// שני פערים אמיתיים שנסגרים כאן:
//
// 1. **אפס מוביל.** 111 מתוך 112 המק"טים מתחילים ב-0 ("0201"). מתקשר
//    שמקיש 201 — התנהגות טבעית לגמרי — לא מצא כלום, כי ההשוואה הייתה
//    מדויקת. ההודעה בטלפון לא אמרה שצריך ארבע ספרות.
//
// 2. 🔴 **מקף במק"ט.** 14 הכרכים של "חת״ס על הש״ס" הם 0301-01 עד
//    0301-14, ואי אפשר להקיש מקף בטלפון. הקוד הסיר ספרות-בלבד מהקלט
//    אך השווה אותו למק"ט *עם* המקף, ולכן אף אחד מ-14 הכרכים לא היה
//    ניתן להזמנה טלפונית — בשקט, בלי שום שגיאה.
//    ראו דפוס זהה: "מק״ט היריד מכיל מקף" (ביטוי \d+ הפיל קטגוריה שלמה).
// ─────────────────────────────────────────────────────────────────────────────

/** ספרות בלבד — כך נראית הקשה בטלפון, וכך מנוטרל כל תו שישבור שאילתה. */
export function digitsOnly(input: string | null | undefined): string {
  return String(input ?? '').replace(/\D/g, '')
}

/**
 * צורת ההשוואה של מק"ט: ספרות בלבד, בלי אפסים מובילים.
 *
 * ⚠️ מסירים אפסים מובילים משני הצדדים (הקלט והמק"ט שבמסד), ולכן
 * "201", "0201" ו-"00201" מתלכדים כולם ל-"201".
 */
export function skuKey(value: string | null | undefined): string {
  return digitsOnly(value).replace(/^0+/, '')
}

/**
 * האם ההקשה מתאימה למק"ט.
 *
 * ⚠️ מק"ט ריק אף פעם אינו מתאים: בלי הבדיקה הזו, הקשה ריקה הייתה
 * מתלכדת עם כל שורה שאין בה מק"ט.
 */
export function skuMatches(typed: string | null | undefined, sku: string | null | undefined): boolean {
  const a = skuKey(typed)
  const b = skuKey(sku)
  return a !== '' && a === b
}

/**
 * הספר שתואם להקשה, או null.
 *
 * 🔴 התאמה מדויקת בלבד (אחרי נרמול) ולא "מתחיל ב-": 0301 ו-0301-01
 * הם שני ספרים שונים, והחזרת "הראשון שמתחיל ב-" הייתה מזמינה את
 * הספר הלא נכון בלי שהמתקשר יידע.
 */
export function matchBookBySku<T extends { sku: string | null }>(
  typed: string | null | undefined,
  books: readonly T[],
): T | null {
  const key = skuKey(typed)
  if (!key) return null
  return books.find(b => skuKey(b.sku) === key) ?? null
}
