// ─────────────────────────────────────────────────────────────────────────────
// חריגה בסדר הדורות — הכלל היחיד במערכת.
//
// 5 הדורות הראשונים הם הליבה המאושרת: הם נכנסו לעץ בייבוא הרשמי בסטטוס
// verified, ולכן *שינוי* בהם הוא דבר שצריך לעצור עליו. מעל דור 5 הנרשם מוסיף
// את אבותיו בעצמו — זה המצב הרגיל והצפוי, ואינו חריגה.
//
// ⚠️ ההבחנה שהייתה חסרה: "אין צומת תואם במאגר" (status = null) אינו שינוי אלא
// *חוסר ידיעה*. הכלל הקודם צבע כל דור ≤5 שאינו verified באדום, ולכן כל משפחה
// שהשרשרת שלה לא נמצאה בהתאמת שמות — כלומר כל מי שנרשם עכשיו — קיבלה התראת
// "סדר הדורות אינו תקין" על דורות שבפועל תקינים לחלוטין. התראה שקופצת לכולם
// היא התראה שאיש אינו קורא, וזה מסוכן יותר מאי-התראה.
//
// מה כן חריגה בדורות 2–5:
//   • rejected — צומת שנבדק ונדחה. בכל דור, לא רק בחמישה הראשונים.
//   • pending  — צומת שאינו חלק מהעץ המאושר. צמתי הייבוא הרשמי נכנסו כ-verified
//                (app/api/admin/lineage/import), ולכן pending בתוך 5 הדורות
//                פירושו צומת שנוסף לתוך הליבה — בדיוק השינוי שמחפשים.
// ─────────────────────────────────────────────────────────────────────────────

/** עומק הליבה המאושרת. מעליו הוספת דורות היא המצב הרגיל. */
export const EARLY_DEPTH = 5

/** סטטוס הצומת בעץ. null = לא נמצא צומת תואם במאגר (חוסר ידיעה). */
export type GenStatus = 'verified' | 'pending' | 'rejected' | null

export type GenColor = 'blue' | 'orange' | 'red'

/**
 * נרמול הסטטוס שמגיע מהמסד (text) לטיפוס — כל ערך שאינו מוכר הוא null.
 *
 * ⚠️ ערך לא מוכר נופל ל-null (לא ידוע) ולא ל-pending: pending הוא "חריגה" בתוך
 * 5 הדורות, ולכן טעות הקלדה בסטטוס הייתה מייצרת התראה על משפחה תקינה.
 */
export function asGenStatus(v: unknown): GenStatus {
  return v === 'verified' || v === 'pending' || v === 'rejected' ? v : null
}

/**
 * האם צומת בעץ נחשב *מאושר* (verified) לצורך צביעה.
 *
 * ⚠️ כלל־על אחד לכל המערכת: צומת ללא סטטוס מפורש (null / undefined / '') נחשב
 * מאושר — בדיוק כפי שהעץ הוויזואלי מציג אותו (`node.status ?? 'verified'`).
 * בלי זה נוצרה סתירה: העץ מראה דור ✓ ירוק, אך הצ'יפ בכרטסת נשאר כתום כי
 * `status === 'verified'` דחה את הצמתים ש־status שלהם ריק. כל בדיקת "מאושר"
 * חייבת לעבור דרך כאן — לא להשוות ידנית ל-'verified'.
 */
export function isNodeVerified(status: unknown): boolean {
  return status == null || status === '' || status === 'verified'
}

/**
 * האם הדור מהווה חריגה — כלומר שינוי אמיתי מול העץ המאושר.
 *
 * דור 1 (החתם סופר) הוא השורש ואינו נבדק.
 */
export function isDeviation(generation: number, status: GenStatus): boolean {
  // ⚠️ דור 1 פטור לחלוטין: הממשק מציג אותו תמיד כמאושר (הוא החתם סופר עצמו),
  // ולכן התראה עליו הייתה מדברת על דור שהצ'יפ שלו כחול.
  if (generation <= 1) return false
  if (status === 'rejected') return true
  if (generation > EARLY_DEPTH) return false
  // ⚠️ החלטה מודעת: גם null ("אין צומת תואם במאגר") הוא חריגה בדורות 2–5.
  //
  // הנימוק שבגללו null הוצא מכאן בעבר נכון: זה חוסר ידיעה ולא שינוי מוכח.
  // אבל התוצאה בשטח הייתה גרועה יותר — כרטיס שנושא תווית "בדיקה מעמיקה" בלי
  // שאף דור צבוע אדום, כלומר מזכיר שרואה התראה ואין לו במה להסתכל. בליבה
  // המאושרת (5 הדורות שנכנסו בייבוא הרשמי כ-verified) "לא מצאנו את האב הזה"
  // הוא בדיוק המצב שדורש עין אנושית, בין אם מקורו בשם שנכתב אחרת ובין אם
  // בסדר דורות שגוי.
  //
  // ⚠️ המחיר ידוע ומקובל: כל נרשם ששרשרתו לא נמצאה בהתאמת שמות יקבל דורות
  // אדומים. אם ההתראה חוזרת לקפוץ לכולם — הפתרון הוא שיפור זיהוי השמות
  // (lib/lineageResolve), לא החזרת null לשקט.
  return status === 'pending' || status === null
}

/**
 * צבע הדור: כחול = מאושר · אדום = חריגה · כתום = ממתין או לא ידוע.
 *
 * ⚠️ אותו כלל משרת את הצ'יפים בכרטסת, את חלונית ההתראה ואת כרטסת היולדות.
 * שלושה עותקים של הכלל היו נפרדים זה מזה בתיקון הראשון, ואז ההתראה הייתה
 * מדברת על דור שהצ'יפים מציגים כתקין.
 */
export function genColor(generation: number, status: GenStatus): GenColor {
  if (status === 'verified') return 'blue'
  return isDeviation(generation, status) ? 'red' : 'orange'
}

/**
 * הדורות החריגים — אלה שמצדיקים את חלונית ההתראה. רשימה ריקה = אין להתריע.
 */
export function deviatingGens(entries: Iterable<[number, GenStatus]>): number[] {
  return [...entries]
    .filter(([g, s]) => isDeviation(g, s))
    .map(([g]) => g)
    .sort((a, b) => a - b)
}
