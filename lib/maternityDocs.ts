// המסמכים שמוצגים בכרטסת היולדת.
//
// 🔴 הבאג שזה מתקן: הכרטסת שלפה ארבעה סוגים בלבד (ת"ז וספחים של הבעל
// והאישה) ברשימה קשיחה. "מסמך אחר", ת"ז ילד, וכל סוג שנוסף מההגדרות
// פשוט לא הופיעו — המסמך היה קיים בכרטסת הצאצא ונעדר מכרטסת היולדת,
// בלי שום סימן שמשהו חסר.
//
// ⚠️ אין כאן רשימת סוגים במכוון. הסינון עצמו היה הבאג, וכל רשימה חדשה
// הייתה חוזרת עליו ברגע שמישהו מוסיף סוג מההגדרות.
//
// ⚠️ אחד לכל סוג (החדש ביותר): כרטסת שמציגה שלוש גרסאות של אותה ת"ז
// מחייבת את המזכירה לנחש איזו עדכנית.
// ─────────────────────────────────────────────────────────────────────────────

export interface MaternityDocRow {
  doc_type: string
  file_url: string | null
  file_name: string | null
  uploaded_at?: string | null
}

/**
 * המסמך העדכני מכל סוג.
 *
 * ⚠️ ממיין בעצמו ואינו מסתמך על סדר השאילתה: הסתמכות כזו נשברת בשקט
 * ברגע שמישהו משנה את ה-order, והכרטסת מציגה מסמך ישן כאילו הוא הנוכחי.
 */
export function pickLatestPerType<T extends MaternityDocRow>(rows: T[]): T[] {
  const best = new Map<string, T>()
  for (const row of rows ?? []) {
    // ⚠️ שורה בלי קובץ מדולגת: אין מה לפתוח, והיא רק תופסת מקום ברשימה.
    if (!String(row.file_url ?? '').trim()) continue
    const current = best.get(row.doc_type)
    if (!current) { best.set(row.doc_type, row); continue }
    // תאריך חסר נחשב הישן ביותר — כך שורה מתועדת תמיד מנצחת שורה בלעדיו.
    const a = String(row.uploaded_at ?? '')
    const b = String(current.uploaded_at ?? '')
    if (a > b) best.set(row.doc_type, row)
  }
  return [...best.values()]
}
