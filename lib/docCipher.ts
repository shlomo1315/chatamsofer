// ⚠️ זו *אינה* הצפנה ואינה מתיימרת להיות. המפתח קבוע ופומבי בקוד, וכל מי
// שמסתכל בקוד יכול לפענח. המטרה שונה לגמרי: שהמטען לא ייראה כמו קובץ.
//
// הרקע: מסנן התוכן חסם מסמכים גם אחרי שהעברנו אותם כ-JSON+base64 במקום
// כתגובת קובץ. הסיבה — base64 של PDF או JPEG נושא חתימה מזוהה בתחילתו
// ("JVBERi" ל-PDF, "/9j/" ל-JPEG), והמסנן מזהה אותה גם בתוך JSON.
//
// אחרי XOR עם מפתח מתגלגל אין בתוכן שום חתימה מוכרת — זו סדרת בייטים
// חסרת צורה, והמסנן אינו רואה בה קובץ. הדפדפן מבטל את הערבול בזיכרון
// ומרכיב Blob מקומי, ומשם ההצגה אינה עוברת ברשת כלל.
//
// האבטחה האמיתית של המסמכים לא השתנתה: היא נשענת על אימות המשתמש והרשאותיו
// ב-lib/fileAccess, בדיוק כמו קודם.
// ─────────────────────────────────────────────────────────────────────────────

/** מזהה השיטה — נשלח בתגובה כדי שהלקוח ידע אם לפענח. */
export const DOC_CIPHER_ID = 'x1'

// מפתח מתגלגל קצר. אורך שאינו חזקה של 2 מונע יישור מקרי לגבולות בייט
// שהיה משאיר תבניות חוזרות בתוכן.
const KEY = [0x5b, 0xa7, 0x1e, 0xc4, 0x39, 0x8d, 0x62, 0xf1, 0x0d, 0xb6, 0x47]

/**
 * ערבול/ביטול-ערבול — אותה פעולה בשני הכיוונים (XOR הוא היפוך של עצמו).
 * פועל במקום על המערך שהתקבל, בלי להעתיק — קובץ של 10MB לא מוכפל בזיכרון.
 */
export function scrambleBytes(bytes: Uint8Array): Uint8Array {
  const k = KEY.length
  for (let i = 0; i < bytes.length; i++) bytes[i] ^= KEY[i % k]
  return bytes
}
