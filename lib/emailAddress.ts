// הטופס מאשר כתובת שהשרת דוחה — והמשתמש מקבל "הרישום נכשל" בלי להבין
// למה. הבדיקה כאן היא אותה בדיקה בשני הצדדים.
//
// ⚠️ המטרה היא לתפוס שגיאת הקלדה, לא לאמת שהתיבה קיימת. אי אפשר לדעת
// מהדפדפן אם כתובת תקינה מבחינה תחבירית באמת מקבלת דואר; הדרך היחידה
// היא לשלוח. לכן הכללים כאן מחמירים על *צורה* ומקלים על תוכן.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * תווי כיווניות ורווחים בלתי-נראים.
 *
 * ⚠️ תקלה חוזרת במערכת: כתובות שהודבקו מ-Word או מ-WhatsApp נושאות
 * תווי RLM/LRM נסתרים. הם שוברים גם את הוולידציה וגם את השליחה
 * בפועל, והמשתמש רואה כתובת שנראית תקינה לחלוטין.
 */
const INVISIBLE = /[​-‏‪-‮⁦-⁩﻿]/g

/** ניקוי לפני כל בדיקה או שמירה: ללא תווים נסתרים, ללא רווחים, אותיות קטנות. */
export function cleanEmail(raw: unknown): string {
  return String(raw ?? '').replace(INVISIBLE, '').trim().toLowerCase()
}

/**
 * ⚠️ מכוונת-רחבה במכוון בחלק המקומי: כתובות אמיתיות מכילות +, נקודות,
 * מקפים וקווים תחתונים. החומרה מרוכזת בדומיין — שם נמצאות כמעט כל
 * שגיאות ההקלדה.
 *
 * הדומיין: תווית אחת לפחות ואז סיומת של 2+ אותיות בלבד. סיומת עם ספרה
 * או מקף אינה קיימת ב-TLD אמיתי, וכך "a@b.c1" נדחה.
 */
const EMAIL_RE = /^[A-Za-z0-9._%+-]+@(?:[A-Za-z0-9](?:[A-Za-z0-9-]*[A-Za-z0-9])?\.)+[A-Za-z]{2,}$/

/** אורך מרבי לפי RFC 5321. מעבר לזה אף שרת דואר לא יקבל. */
const MAX_LEN = 254

/**
 * מחזיר הודעת שגיאה בעברית, או מחרוזת ריקה כשהכתובת תקינה.
 *
 * ⚠️ הודעה ספציפית ולא "כתובת לא תקינה" גנרי: מי שכתב "שם@gmail" צריך
 * לדעת שחסרה הסיומת, אחרת הוא מקליד שוב את אותו הדבר.
 */
export function emailError(raw: unknown): string {
  const v = cleanEmail(raw)

  if (!v) return 'נא להזין כתובת מייל'
  if (v.length > MAX_LEN) return 'הכתובת ארוכה מדי'

  const at = v.split('@')
  if (at.length < 2) return 'חסר @ בכתובת'
  if (at.length > 2) return 'יש יותר מ-@ אחד בכתובת'

  const [local, domain] = at
  if (!local) return 'חסר השם לפני ה-@'
  if (!domain) return 'חסר שם הדומיין אחרי ה-@'
  if (!domain.includes('.')) return 'חסרה סיומת בדומיין (לדוגמה ‎.com)'
  // ⚠️ נקודה כפולה או נקודה בקצה עוברות את הבדיקה הכללית ברוב הביטויים
  // הנאיביים, ולכן נבדקות במפורש.
  if (v.includes('..')) return 'יש שתי נקודות רצופות בכתובת'
  if (local.startsWith('.') || local.endsWith('.')) return 'הכתובת אינה יכולה להתחיל או להסתיים בנקודה לפני ה-@'

  if (!EMAIL_RE.test(v)) return 'כתובת המייל אינה תקינה'
  return ''
}

/** בדיקה בוליאנית — לנתיבים שאין בהם הודעה למשתמש. */
export const isValidEmail = (raw: unknown): boolean => !emailError(raw)
