// לאישור מנהל" ללא סיבה.
//
// ⚠️ מנגנון השחרור הקיים ב-/api/admin/lineage/assign דורש שכל דורות
// 2–5 יהיו verified — אבל רק 348 מתוך 11,331 הצמתים מאומתים, ולכן הוא
// כמעט לעולם אינו משחרר. הבדיקה כאן היא השלמה: היא שואלת אם התנאי
// שיצר את הדגל בכלל מתקיים, ולא אם היחוס אומת.
// ─────────────────────────────────────────────────────────────────────────────

/** עומק הדורות שנחשב "רדוד" — סטייה בתוכו מחייבת בדיקה מעמיקה. */
export const NORMAL_DEPTH = 5

export interface DeepReviewState {
  status: string | null
  /** הדור של הצומת המשויך. null = אין שיוך. */
  generation: number | null
  /** כמה צמתים ידניים הנרשם הוסיף */
  manualCount: number
  /** סיבה שהמזכיר כתב ידנית — קיומה הופך את הדגל למכוון */
  reason: string | null
}

/**
 * האם הדגל תקוע בטעות וניתן לשחרר ל-pending.
 *
 * ⚠️ שלושת התנאים נדרשים יחד. די באחד מהם כדי שהדגל יהיה לגיטימי:
 *   · סיבה שנכתבה ידנית → המזכיר החליט, לא המערכת
 *   · צמתים ידניים → הנרשם באמת הוסיף יחוס
 *   · דור רדוד → הסטייה בתוך חמשת הדורות הראשונים
 */
export function isDeepReviewStuck(s: DeepReviewState): boolean {
  if (s.status !== 'deep_review') return false

  // המזכיר העביר ידנית וכתב סיבה — לא נוגעים.
  if ((s.reason ?? '').trim()) return false

  // הנרשם הוסיף צמתים — הסטייה אמיתית.
  if (s.manualCount > 0) return false

  // ⚠️ בלי שיוך לצומת אין דרך לדעת אם הסטייה רדודה. משאירים — שחרור
  // על סמך חוסר מידע היה מסתיר משפחה שדווקא כן חורגת.
  if (s.generation == null) return false

  // הצומת עמוק מ-5 → התנאי שיצר את הדגל אינו מתקיים.
  return s.generation >= NORMAL_DEPTH
}
