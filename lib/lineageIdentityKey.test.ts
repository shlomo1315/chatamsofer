import { describe, it, expect } from 'vitest'
import { lineageIdentityKey } from './lineageNameFormat'

const same = (a: string, b: string) =>
  expect(lineageIdentityKey(a)).toBe(lineageIdentityKey(b))
const differ = (a: string, b: string) =>
  expect(lineageIdentityKey(a)).not.toBe(lineageIdentityKey(b))

describe('lineageIdentityKey — הכפילויות שנמצאו בפועל בייצור', () => {
  // 🔴 המקרה שיצר 4 עותקים תחת "רבי יוסף ורייזל ברנפלד"
  it('"ומרת גיטל" ו-"וגיטל" הם אותו אדם', () => {
    same('רבי יהודה ומרת גיטל ברנדייס', 'רבי יהודה וגיטל ברנדייס')
  })

  it('"שיחיו" בסוף אינו יוצר אדם חדש', () => {
    same('רבי יוסף ושפרה ברנדייס שיחיו', 'רבי יוסף ושפרה ברנדייס')
  })

  it('תואר הבעל אינו משנה זהות', () => {
    same('רבי משה כהן', 'הרב משה כהן')
    same('רבי משה כהן', 'משה כהן')
  })

  it('גרשיים, רווחים כפולים ורישיות אינם משנים זהות', () => {
    same('רבי שלמה זלמן ליברמן', 'רבי  שלמה   זלמן  ליברמן')
    same('רבי יצחק צבי פריי', 'רבי יצחק צבי פריי ')
  })

  it('תואר האישה הישן והחדש מצטמצמים לאותו מפתח', () => {
    same('רבי יהודה והרבנית גיטל ברנדייס', 'רבי יהודה ומרת גיטל ברנדייס')
  })
})

// ⚠️ החלק החשוב יותר: מיזוג שני אנשים שונים מוחק אדם מהעץ — טעות יקרה
// בהרבה מכפילות. המפתח חייב להישאר שמרני.
describe('lineageIdentityKey — לא ממזג אנשים שונים', () => {
  it('שם אישה שונה = אדם אחר', () => {
    differ('רבי יהודה ומרת גיטל ברנדייס', 'רבי יהודה ומרת שרה ברנדייס')
  })

  it('שם משפחה שונה = אדם אחר', () => {
    differ('רבי יהודה ומרת גיטל ברנדייס', 'רבי יהודה ומרת גיטל ברנפלד')
  })

  it('שם פרטי שני שונה = אדם אחר', () => {
    differ('רבי יוסף ברנדייס', 'רבי יוסף חיים ברנדייס')
    differ('רבי שלמה זלמן ליברמן', 'רבי שלמה ליברמן')
  })

  it('נשוי מול רווק אינם אותו רשומה', () => {
    differ('רבי יוסף ושפרה ברנדייס', 'רבי יוסף ברנדייס')
  })

  it('ערך ריק אינו תואם שם אמיתי', () => {
    expect(lineageIdentityKey('')).toBe('')
    expect(lineageIdentityKey(null)).toBe('')
    differ('רבי משה כהן', '')
  })

  // ⚠️ מילה שמתחילה ב-ו' ואינה ו' חיבור — לא לחתוך אותה בטעות
  it('שם שמתחיל ב-ו נשמר', () => {
    differ('רבי וולף כהן', 'רבי אולף כהן')
    expect(lineageIdentityKey('רבי וולף כהן')).toContain('ולף')
  })
})
