// וכפילות במלאי או בכסף.
// ─────────────────────────────────────────────────────────────────────────────

export const DEPLOY_HINT =
  'הפעולה לא הושלמה — ייתכן שהאתר באמצע עדכון גרסה, או שיש תקלת רשת. ' +
  'נסו שוב בעוד רגע, ובדקו אם הפעולה בכל זאת בוצעה.'

/** דפוסי כשל שאינם שגיאת שרת אלא ניתוק/החלפת שרת. */
const NETWORK_RE = /failed to fetch|networkerror|load failed|fetch failed|network request failed/i

/**
 * ההודעה שתוצג למשתמש.
 *
 * ⚠️ שגיאה שהשרת ניסח (למשל "אין הרשאה") מוצגת כפי שהיא — היא מדויקת יותר
 * מכל נוסח כללי, והחלפתה הייתה מסתירה את הסיבה האמיתית.
 */
export function networkErrorMessage(e: unknown): string {
  if (typeof e === 'string' && e.trim()) return e
  if (e instanceof Error) {
    if (e.name === 'AbortError') return DEPLOY_HINT
    const m = e.message?.trim() ?? ''
    if (!m || NETWORK_RE.test(m)) return DEPLOY_HINT
    return m
  }
  return DEPLOY_HINT
}
