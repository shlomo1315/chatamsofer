import { describe, it, expect } from 'vitest'
import { generationLabel } from './generationLabel'

// ─────────────────────────────────────────────────────────────────────────────
// בטופס אישור רב, שורת "דור 10:" הופיעה על הדף כ-"דור 01:".
//
// השורש: pdf-lib מצייר גליפים תו-אחר-תו בכיוון ציור אחיד ואינו מיישם
// bidi. במחרוזת עברית (RTL) הציור הוא מימין לשמאל, ולכן רצף ספרות
// שנכתב "10" יוצא על הדף כ-"01".
//
// ⚠️ ניסיון ראשון עם LRM (U+200E) נכשל: pdf-lib אינו מפרש תווי כיווניות
// כלל, ותו רוחב-אפס אינו משפיע עליו. אומת בעין — הטופס עדיין הציג 01.
// הפתרון הוא היפוך מפורש, בדיוק כמו שכבר נעשה בקובץ עבור הסוגריים
// והמטבע: ")בן(" בקוד מצויר כ-"(בן)" על הדף.
//
// 🔴 הטסט בודק את המחרוזת שנשלחת לציור — לא את הפלט. הפלט נבדק בעין,
// כי הפקת טקסט מ-PDF מציגה סדר לוגי ומטעה בשני הכיוונים.
// ─────────────────────────────────────────────────────────────────────────────

describe('generationLabel', () => {
  it('🔴 הרגרסיה: דור 10 נשלח לציור כ-"01" כדי לצאת "10" על הדף', () => {
    expect(generationLabel(10)).toBe('דור 01:')
  })

  it('ספרה בודדת אינה מושפעת — 1-9 היו תקינים תמיד', () => {
    expect(generationLabel(1)).toBe('דור 1:')
    expect(generationLabel(9)).toBe('דור 9:')
  })

  it('דורות דו-ספרתיים נוספים', () => {
    expect(generationLabel(11)).toBe('דור 11:')  // פלינדרום — זהה בשני הכיוונים
    expect(generationLabel(12)).toBe('דור 21:')
    expect(generationLabel(19)).toBe('דור 91:')
    expect(generationLabel(20)).toBe('דור 02:')
  })

  it('תלת-ספרתי — לא צפוי בייחוס, אך אינו שובר', () => {
    expect(generationLabel(123)).toBe('דור 321:')
  })

  it('שומר על המילה "דור" ועל הנקודתיים', () => {
    // ⚠️ הנקודתיים אינן מתהפכות — ראה ההערה ב-rabbiFormPdf. הפקת הטקסט
    // מציגה אותן בסדר הלוגי וזה *נראה* כבאג, אך הרינדור תקין.
    expect(generationLabel(3).startsWith('דור ')).toBe(true)
    expect(generationLabel(3).endsWith(':')).toBe(true)
  })
})
