// ─────────────────────────────────────────────────────────────────────────────
// בקשת תיקון סדר דורות מהאזור האישי.
//
// ⚠️ עד כה ההצעות היו אפשריות רק דרך lineage_share_invites — קישור עם
// טוקן שהמזכירות שולחת ביוזמתה. צאצא שראה טעות בייחוס שלו לא יכול היה
// להודיע עליה, אלא אם המשרד פנה אליו קודם. הייחוס קובע זכאות, וטעות בו
// שלא ניתן לדווח עליה נשארת בעץ.
//
// ⚠️ הבקשה אינה משנה את העץ: היא נכנסת ל-lineage_review_suggestions
// כ-kind='note' וממתינה לאישור המנהל, כמו כל הצעה אחרת. עריכה ישירה
// בידי המבקש הייתה עוקפת את הבדיקה שהייחוס כולו נשען עליה.
// ─────────────────────────────────────────────────────────────────────────────

export const MAX_FIX_TEXT = 1000
const MIN_FIX_TEXT = 10

/**
 * מנקה טקסט חופשי לפני שמירה.
 *
 * ⚠️ מסיר תגיות HTML: ההצעה מוצגת למנהל במסך הניהול, וטקסט שנשמר כפי
 * שהוא הוא וקטור הזרקה. אין כאן צורך בשום תגית — זהו תיאור בשפה חופשית.
 */
export function cleanFixText(input: unknown): string {
  return String(input ?? '')
    .replace(/<[^>]*>/g, '')
    .replace(/[<>]/g, '')
    .trim()
    .slice(0, MAX_FIX_TEXT)
}

/**
 * מאמת את הבקשה. מחזיר הודעת שגיאה, או null כשתקינה.
 *
 * ⚠️ אורך מזערי: "טעות" או "לא נכון" אינם בקשת תיקון — המנהל אינו יכול
 * לפעול לפיהם, והפנייה חוזרת אליו כשאלה במקום כמשימה.
 */
export function validateFixRequest(text: unknown): string | null {
  const t = cleanFixText(text)
  if (t.length < MIN_FIX_TEXT) {
    return `נא לפרט מה צריך לתקן (לפחות ${MIN_FIX_TEXT} תווים) — למשל: באיזה דור, ומה השם הנכון`
  }
  if (String(text ?? '').trim().length > MAX_FIX_TEXT) {
    return `הפירוט ארוך מדי (עד ${MAX_FIX_TEXT} תווים)`
  }
  return null
}
