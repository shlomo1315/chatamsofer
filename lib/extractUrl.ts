// ─────────────────────────────────────────────────────────────────────────────
// שליפת הקישור מתוך טקסט שהודבק.
//
// ⚠️ נציגי בתי ההחלמה אינם מדביקים קישור נקי. הם מדביקים את כל ההודעה שקיבלו
// ("שלום, מצורפת הקבלה: https://... בברכה, ..."), ולעיתים גם עם סימני כיווניות
// ורווחים בלתי-נראים שווטסאפ ותוכנות דוא"ל מזריקות לטקסט. השדה שלח את הכל
// כמות שהוא, new URL נכשל, והנציג קיבל "הקישור אינו תקין" בלי להבין למה —
// הרי הקישור *כן* היה שם מול העיניים.
//
// לכן: שולפים את הקישור הראשון מתוך הטקסט, ומשאירים לנציג להדביק מה שנוח לו.
// ─────────────────────────────────────────────────────────────────────────────

// עוצר ברווח ובתווים שעוטפים קישור במשפט — סוגריים, מרכאות, סוגר מסולסל.
const URL_IN_TEXT = /(?:https?:\/\/|www\.)[^\s<>"'`\])}]+/i

// סימני כיווניות ורווחים בלתי-נראים — מוחלפים ברווח כדי שלא יידבקו לקישור
// ויהפכו אותו ללא תקין (התו קיים במחרוזת אך אינו נראה למי שהדביק).
const INVISIBLE = /[​-‏‪-‮⁦-⁩﻿ ]/g

// פיסוק נגרר שנדבק לסוף הקישור כשהוא מופיע בתוך משפט ("...בקישור הזה: <url>.")
const TRAILING_PUNCT = /[.,;:!?"'׳״|]+$/

/**
 * מחזיר את הקישור הראשון שנמצא בטקסט, מנוקה מפיסוק נגרר.
 * אם לא נמצא קישור — מחזיר את הטקסט המקורי (מקוצץ), כדי שהשגיאה שתוצג
 * תתייחס למה שהמשתמש באמת הזין ולא למחרוזת ריקה.
 */
export function extractUrl(raw: string | null | undefined): string {
  const s = String(raw ?? '').replace(INVISIBLE, ' ')
  if (!s.trim()) return ''
  const m = s.match(URL_IN_TEXT)
  if (!m) return s.trim()
  const url = m[0].replace(TRAILING_PUNCT, '')
  // קישור שהודבק בלי סכימה ("www.example.com/x.pdf") — fetch דורש סכימה מלאה
  return /^www\./i.test(url) ? `https://${url}` : url
}
