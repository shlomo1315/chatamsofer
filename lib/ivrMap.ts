export type IvrKind = 'menu' | 'input' | 'action' | 'readout'

export interface IvrNode {
  /** מזהה יציב — משמש למפתח React ולזיהוי בהרחבות עתידיות. */
  id: string
  title: string
  /** מה השלוחה עושה, במשפט או שניים. */
  what: string
  kind: IvrKind
  /** מה המתקשר מקיש כאן. ריק = אין קלט. */
  input?: string
  children?: IvrNode[]
}

export interface IvrExtension {
  id: string
  title: string
  /** מה השלוחה נועדה לעשות. */
  purpose: string
  /** נתיב ה-webhook בימות. */
  webhook: string
  /** סוג השלוחה בהגדרות ימות. */
  yemotType: string
  /** מפתח ההודעות לעריכה, אם יש. */
  messagesKey: 'holiday' | 'maternity' | null
  /** משתני סביבה שהשלוחה תלויה בהם. */
  env: string[]
  /** הערות תפעול שחשוב שהמנהל ידע. */
  notes: string[]
  /**
   * 🔴 שיחה *יוצאת* — אנחנו מחייגים אל המשפחה, לא היא אלינו.
   *
   * ⚠️ ההבחנה אינה קוסמטית: הצגת מסלול יוצא בתוך עץ התפריט מתארת מסלול
   * שאיש אינו עובר, ומי שמחפש "למה לא הגיע הקוד" מחפש במקום הלא נכון.
   */
  outbound?: boolean
  tree: IvrNode[]
}

