// תווית שורת דור בטופס אישור רב ("דור 10:").
//
// 🔴 הבאג שזה מתקן: "דור 10:" הופיע על הדף כ-"דור 01:".
//
// pdf-lib מצייר תווים לפי סדרם במחרוזת ואינו מיישם את אלגוריתם ה-bidi
// של יוניקוד. בתוך מחרוזת עברית, רצף ספרות הוא מקטע LTR מוטבע — ובלי
// סימון כיווניות מפורש הוא נצבע בכיוון הסביבה, כלומר מצויר הפוך.
//
// ⚠️ דורות 1-9 הסתירו את הבאג לגמרי: ספרה בודדת נראית זהה בשני הכיוונים.
// הוא נחשף רק במשפחה בת עשרה דורות ומעלה — כלומר דווקא בייחוס הארוך,
// שהוא המקרה שהטופס הזה נועד לו.
//
// הפתרון: עטיפת המספר ב-LRM (U+200E), סימון רוחב-אפס שמקבע את הרצף
// ככיוון שמאל-לימין בלי להוסיף רווח או גליף נראה.
//
// ⚠️ למה לא להפוך את הספרות ידנית (כמו שנעשה בסוגריים ובמטבע): היפוך
// ידני עובד רק כשידוע מראש אורך הרצף וכיוון הסביבה, והוא נשבר בכל
// שינוי הקשר. LRM מטפל בכיווניות בשכבה הנכונה — בטקסט עצמו.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * ⚠️ נשמר לתאימות בלבד — אינו בשימוש עוד.
 *
 * 🔴 LRM לא פתר את הבאג: pdf-lib אינו מפרש תווי כיווניות כלל. הוא מצייר
 * גליפים לפי סדרם במחרוזת, ותו רוחב-אפס פשוט אינו משפיע עליו. אומת
 * בעין: אחרי הוספת ה-LRM הטופס עדיין הציג "דור 01:".
 */
export const LRM = '‎'

/**
 * 🔴 הספרות מסודרות בסדר הפוך במכוון.
 *
 * pdf-lib מצייר תו-אחר-תו בכיוון ציור אחיד ואינו מיישם bidi. במחרוזת
 * עברית (RTL) המנוע מצייר את התווים מימין לשמאל — ולכן רצף ספרות
 * שנכתב "10" יוצא על הדף כ-"01".
 *
 * ⚠️ זה בדיוק הדפוס שכבר קיים בקובץ עבור הסוגריים והמטבע: ")בן(" בקוד
 * מצויר כ-"(בן)" על הדף. אותו היפוך, אותה סיבה.
 *
 * ⚠️ ספרה בודדת אינה מושפעת (1-9 היו תקינים תמיד) — reverse על תו אחד
 * מחזיר אותו עצמו, ולכן אין צורך בתנאי מיוחד.
 *
 * 🔴 אימות חובה בעין. הפקת טקסט מ-PDF מציגה סדר *לוגי*, כלומר המחרוזת
 * ההפוכה כאן תיראה שם "שבורה" בעוד שעל הדף היא תקינה — ולהפך. אל
 * "תתקן" את השורה הזו לפי הפקת טקסט.
 */
export function generationLabel(generation: number): string {
  const digits = String(generation).split('').reverse().join('')
  return `דור ${digits}:`
}
