// כל אות עברית היא שני בייטים, וכל בייט הופך לשלושה תווים ("א" ‑> "%D7%90").
// גוף הטופס — 1,726 תווים בלבד — הפך ל-URL של 8,411 תווים, ו-Gmail דחה
// אותו. הפונה ראה דף לבן.
//
// ⚠️ זו מגבלה של Gmail ולא שלנו. אי אפשר "לתקן" אותה — אפשר רק להיכנס
// אליה. וכל שיפוט על אורך חייב להיעשות על ה-URL **המקודד**: 442 תווי גוף
// הם כבר 2,454 תווי URL.
//
// ⚠️ הגוף עצמו נבנה ב-buildDraftBodyCompact (emailRequestForms) — שם הוא
// יושב לצד fieldsFor ו-parseDraft, כדי שמי שמשנה שדה יראה מיד את שני
