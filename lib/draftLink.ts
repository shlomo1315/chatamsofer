/**
 * מגבלת אורך בטוחה לקישור טיוטה.
 *
 * 🔴 נקבע ממדידה ולא מניחוש: קישור בן 8,411 תווים נדחה בשדה. קישורים
 * קצרים יותר עבדו ועובדים.
 *
 * ⚠️ 5,000 ולא 4,000: הערך המקורי נגזר מקישור **Gmail בדפדפן**, שבו
 * המגבלה חמורה יותר. הקישור עבר מאז ל-mailto:, שנפתח בתוכנת המייל של
 * הפונה — הקשר שונה, עם מגבלה רופפת בהרבה.
 *
 * 🔴 הרף הועלה כדי לא לקצץ תוכן שהפונה חייב. קיצוץ ההנחיות הוא בדיוק
 * מה ששבר את ההגשה בעבר: טופס בלי שדה = בקשה שנקלטת ריקה. גם 5,000
 * הוא פחות משני שלישים ממה שנכשל בפועל.
 */
export const GMAIL_URL_SAFE_LIMIT = 5000

export interface ComposeLink {
  to: string
  subject: string
  body?: string
}

/**
 * קישור חלון כתיבה ב-Gmail.
 *
 * 🔴 /u/0/ חובה. בלעדיו Gmail מחזיר "Bad Request · Error 400" —
 * הנתיב /mail/?view=cm אינו תקף.
 *
 * 🔴 ולא mailto: — Gmail חוסם mailto שנלחץ מתוך גוף הודעה, והתוצאה
 * דף לבן. כל הקהל שלנו קורא את הדואר בתוך Gmail.
 */
export function gmailComposeLink({ to, subject, body }: ComposeLink): string {
  // ⚠️ נושא/גוף ריקים אינם נשלחים כלל: su= ריק מוצג למשתמש כשדה שהוגדר
  // במפורש כריק, וזה שונה מלא-להגדיר-אותו.
  const p = new URLSearchParams({ view: 'cm', fs: '1', to })
  if (subject) p.set('su', subject)
  if (body) p.set('body', body)
  return `https://mail.google.com/mail/u/0/?${p.toString()}`
}
