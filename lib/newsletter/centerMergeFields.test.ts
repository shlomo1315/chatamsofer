import { describe, it, expect } from 'vitest'
import { buildMergeData, MERGE_TAGS, applyMerge, unknownTags } from './merge'

// ─────────────────────────────────────────────────────────────────────────────
// 🔴 שדות המוקד בניוזלטר — כל משפחה מקבלת את המוקד *שלה*.
//
// ⚠️ בלי זה אי אפשר לשלוח הודעה אחת ל-6,106 משפחות: המוקד, הכתובת והשעות
// שונים בין 26 המוקדים, ומשפחה שקיבלה את הכתובת של מוקד אחר מגיעה למקום
// הלא נכון. עד כה נשלחה או הודעה כללית בלי כתובת, או 26 קמפיינים נפרדים.
//
// ⚠️ הערכים מגיעים מ-merge_data — סנאפשוט שנשמר בזמן מימוש הסגמנט. מוקד
// שייפתח או ישתנה אחרי המימוש לא ישנה מייל שכבר נשלח, וזו ההתנהגות
// הנכונה: המשפחה קיבלה כתובת, והיא חייבת להישאר נכונה.
// ─────────────────────────────────────────────────────────────────────────────

describe('🔴 שדות המוקד קיימים בבורר', () => {
  for (const token of ['מוקד', 'מוקד_כתובת', 'מוקד_שעות', 'מוקד_עיר', 'מוקד_סטטוס']) {
    it(`{{${token}}} מוצע למשתמש`, () => {
      expect(MERGE_TAGS.some(t => t.token === token)).toBe(true)
    })
  }

  it('אינם מסומנים כמשתנה לא מוכר', () => {
    expect(unknownTags('{{מוקד}} {{מוקד_כתובת}} {{מוקד_שעות}} {{מוקד_עיר}}')).toEqual([])
  })
})

describe('🔴 buildMergeData — פרטי המוקד של המשפחה', () => {
  const src = {
    family_name: 'כהן', full_name: 'משה',
    center_name: 'אזור סקולוב', center_city: 'בני ברק',
    center_address: 'יואל 6 קומה 2', center_hours: 'ימי רביעי וחמישי, 16:00–23:00',
  }

  it('שם המוקד כולל את העיר — כמו שנאמר בטלפון ומודפס בשובר', () => {
    expect(buildMergeData(src)['מוקד']).toBe('בני ברק, אזור סקולוב')
  })

  it('כתובת ושעות נפרדות — כדי שאפשר יהיה לעצב אותן במייל', () => {
    const d = buildMergeData(src)
    expect(d['מוקד_כתובת']).toBe('יואל 6 קומה 2')
    expect(d['מוקד_שעות']).toBe('ימי רביעי וחמישי, 16:00–23:00')
    expect(d['מוקד_עיר']).toBe('בני ברק')
  })

  it('עיר ששמה זהה לשם המוקד אינה נאמרת פעמיים', () => {
    expect(buildMergeData({ center_city: 'אשדוד', center_name: 'אשדוד' })['מוקד']).toBe('אשדוד')
  })

  // 🔴 משפחה שטרם בחרה מוקד — אסור שיישאר "{{מוקד}}" גולמי במייל.
  it('בלי מוקד — ריק ולא תגית גולמית', () => {
    const d = buildMergeData({ family_name: 'לוי' })
    expect(d['מוקד']).toBe('')
    expect(applyMerge('המוקד שלכם: {{מוקד}}', d)).toBe('המוקד שלכם: ')
  })
})

// ─────────────────────────────────────────────────────────────────────────────
// 🔴 מוקד שטרם החל לחלק — טקסט אחר לגמרי.
//
// ⚠️ 22 מתוך 26 המוקדים עדיין סגורים (4,651 משפחות). מייל שאומר "הכרטיס
// ממתין לכם, בואו לאסוף" למשפחה שהמוקד שלה סגור שולח אותה לדלת נעולה.
// ─────────────────────────────────────────────────────────────────────────────
describe('🔴 {{מוקד_סטטוס}} — מבדיל בין מחלק לטרם מחלק', () => {
  const base = { center_name: 'אזור סקולוב', center_city: 'בני ברק' }

  it('מוקד שנפתח לחלוקה', () => {
    expect(buildMergeData({ ...base, center_pickup_open: true })['מוקד_סטטוס']).toBe('מחלק')
  })

  it('מוקד שטרם נפתח', () => {
    expect(buildMergeData({ ...base, center_pickup_open: false })['מוקד_סטטוס']).toBe('טרם מחלק')
  })

  it('בלי מוקד כלל — ריק, כדי שתנאי לא יתפוס אותו כאחד מהשניים', () => {
    expect(buildMergeData({ family_name: 'לוי' })['מוקד_סטטוס']).toBe('')
  })
})

// ─────────────────────────────────────────────────────────────────────────────
// 🔴 בלוק מותנה — פסקה שלמה שמופיעה רק למי שהמוקד שלו פתוח (או סגור).
//
// ⚠️ שדה סטטוס לבדו אינו מספיק: המנהל צריך לכתוב *פסקאות שונות* לשני
// המצבים — "הכרטיס ממתין, הנה הכתובת והשעות" מול "נעדכן כשהמוקד ייפתח".
// בלי זה הוא נאלץ לשלוח שני קמפיינים נפרדים ולסנן ידנית, וטעות בסינון
// שולחת משפחה לדלת נעולה.
// ─────────────────────────────────────────────────────────────────────────────
describe('🔴 בלוק מותנה {{#אם_מוקד_מחלק}}', () => {
  const open = buildMergeData({ center_name: 'סקולוב', center_city: 'בני ברק', center_pickup_open: true })
  const shut = buildMergeData({ center_name: 'חיפה', center_city: 'חיפה', center_pickup_open: false })
  const tpl = '{{#אם_מוקד_מחלק}}בואו לאסוף ב{{מוקד}}{{/אם_מוקד_מחלק}}'
    + '{{#אם_מוקד_טרם_מחלק}}נעדכן אתכם בקרוב{{/אם_מוקד_טרם_מחלק}}'

  it('מוקד פתוח — רק הפסקה שלו, והמשתנים בתוכה מוזרקים', () => {
    expect(applyMerge(tpl, open)).toBe('בואו לאסוף בבני ברק, סקולוב')
  })

  it('מוקד סגור — רק הפסקה השנייה', () => {
    expect(applyMerge(tpl, shut)).toBe('נעדכן אתכם בקרוב')
  })

  it('בלי מוקד — שתי הפסקאות יורדות, ולא נשאר תחביר גולמי', () => {
    const none = buildMergeData({ family_name: 'לוי' })
    expect(applyMerge(tpl, none)).toBe('')
  })

  it('בלוק על פני כמה שורות', () => {
    const multi = '{{#אם_מוקד_מחלק}}\nכתובת: {{מוקד_כתובת}}\nשעות: {{מוקד_שעות}}\n{{/אם_מוקד_מחלק}}'
    expect(applyMerge(multi, buildMergeData({
      center_name: 'סקולוב', center_pickup_open: true,
      center_address: 'יואל 6', center_hours: '16:00-23:00',
    }))).toBe('\nכתובת: יואל 6\nשעות: 16:00-23:00\n')
  })

  it('תחביר הבלוקים אינו נספר כמשתנה לא מוכר', () => {
    expect(unknownTags(tpl)).toEqual([])
  })
})
