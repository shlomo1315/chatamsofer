import { describe, it, expect } from 'vitest'
import { fullestOf, type QuickNode } from '@/app/admin/lineage/QuickReview'

// ⚠️ מה שנבדק כאן הוא ברירת המחדל לשם שיישאר אחרי מיזוג. הצומת ששורד נבחר לפי
// מספר ילדים ואימות, ואין לזה שום קשר לאיכות ניסוח השם — בלי ההפרדה הזאת מיזוג
// היה מוחק בשקט את שם האישה או את התואר, וזה מידע שאי אפשר לשחזר מהעץ.

const n = (name: string): QuickNode =>
  ({ id: name, name, status: 'pending', relation: 'son', children: 0, families: 0 })

describe('ברירת המחדל לשם שיישאר', () => {
  it('הניסוח עם שם האישה מנצח', () => {
    expect(fullestOf([n('רבי עקיבא קוריניצר'), n('רבי עקיבא ורייזל קוריניצר')]))
      .toBe('רבי עקיבא ורייזל קוריניצר')
  })

  it('לא תלוי בסדר הקבוצה', () => {
    expect(fullestOf([n('רבי יואל ומרת ברנה שרייבר'), n('רבי יואל שרייבר')]))
      .toBe('רבי יואל ומרת ברנה שרייבר')
  })

  it('במספר מילים זהה — הארוך יותר', () => {
    // "אליעזר" מול "אלעזר": אותו מספר מילים, וההעדפה לניסוח המלא יותר.
    expect(fullestOf([n('רבי אלעזר כהן'), n('רבי אליעזר כהן')])).toBe('רבי אליעזר כהן')
  })

  it('קבוצה ריקה אינה מפילה', () => {
    expect(fullestOf([])).toBe('')
  })
})
