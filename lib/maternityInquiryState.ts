// ─────────────────────────────────────────────────────────────────────────────
// מצב הבירור של תיק יולדת — מקור אמת יחיד.
//
// 🔴 תיק שנשלח אליו בירור צריך לרדת מרשימת "ממתין לאישור": הכדור אצל
// היולדת, ואין מה לעשות איתו עד שהיא תענה. כשהיא עונה — הוא חוזר
// לרשימה עם תווית "חזר מבירור" מהבהבת.
//
// ⚠️ בניגוד להלוואות, כאן *אין* סטטוס inquiry ב-maternity_aids. הסטטוס
// נשאר pending / deep_review, וההבחנה נגזרת משרשור ההודעות בלבד:
//   · ההודעה האחרונה מהמזכירות → ממתינים ליולדת (יורד מהרשימה)
//   · ההודעה האחרונה מהיולדת   → חזר מבירור (עולה עם תווית)
//   · אין הודעות כלל            → תיק רגיל
//
// זו הסיבה שהמודול הזה קיים ולא בדיקה מקומית: אותו כלל משרת את הרשימה,
// את המונה ואת התווית, ושלושה מימושים היו נסחפים.
// ─────────────────────────────────────────────────────────────────────────────

/** המידע המינימלי שהמצב נגזר ממנו. */
export interface InquiryStateInput {
  /**
   * כיוון ההודעה האחרונה בשרשור.
   * 'staff' = המזכירות שלחה · 'applicant' = היולדת השיבה.
   * null/undefined = אין שרשור בכלל.
   */
  lastDirection?: string | null
}

/** נשלח בירור והיולדת עדיין לא ענתה — הכדור אצלה. */
export const isAwaitingReply = (a: InquiryStateInput): boolean =>
  a.lastDirection === 'staff'

/**
 * 🔴 היולדת השיבה — התיק ממתין *לנו* וחוזר לרשימה עם תווית מהבהבת.
 * בלי זה התשובה נבלעת: התיק נראה כמו כל תיק אחר, ואיש לא יודע שיש
 * מענה שממתין.
 */
export const isReturnedFromInquiry = (a: InquiryStateInput): boolean =>
  a.lastDirection === 'applicant'

/**
 * האם התיק מוצג ברשימת ההמתנה.
 *
 * ⚠️ תיק שממתין לתשובת היולדת יורד מהרשימה — אחרת הוא תופס מקום בתור
 * ומטעה: הוא נראה כמשימה פתוחה בזמן שאין מה לעשות איתו.
 */
export const showsInPendingList = (a: InquiryStateInput): boolean =>
  !isAwaitingReply(a)
