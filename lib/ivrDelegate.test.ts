import { describe, it, expect } from 'vitest'
import { resolveRoute, ROUTE_PARAM } from './ivrDelegate'

// ─────────────────────────────────────────────────────────────────────────────
// 🔴 ניתוב פנימי בשלוחה הראשית.
//
// עד כה ההעברה נעשתה ב-go_to_folder — ימות העבירה את השיחה לשלוחה אחרת,
// והמשך השיחה כבר לא עבר דרכנו. עכשיו הכל רץ תחת כתובת אחת, ולכן צריך
// לזכור *באיזה מסלול* השיחה נמצאת.
//
// 🔴 ימות אינה שומרת מצב בין קריאות. המסלול מוחזר אליה כמשתנה וחוזר
// בקריאה הבאה; בלעדיו כל הקשה הייתה מתחילה מחדש מהתפריט הראשי, והמתקשר
// היה תקוע בלולאה בלי להבין למה.
// ─────────────────────────────────────────────────────────────────────────────

describe('resolveRoute — הקשה ראשונה', () => {
  it('אין מסלול ואין הקשה — נשארים בתפריט', () => {
    expect(resolveRoute({}, '')).toBeNull()
  })

  it('הקשה 1 → חגים', () => {
    expect(resolveRoute({}, '1')).toBe('holiday')
  })

  it('הקשה 2 → יולדות', () => {
    expect(resolveRoute({}, '2')).toBe('maternity')
  })

  it('⚠️ הקשה 9 אינה מסלול — היא הודעה שמטופלת בתפריט עצמו', () => {
    expect(resolveRoute({}, '9')).toBeNull()
  })

  it('הקשה שאינה בתפריט — נשארים בתפריט', () => {
    expect(resolveRoute({}, '7')).toBeNull()
    expect(resolveRoute({}, 'x')).toBeNull()
  })
})

describe('resolveRoute — 🔴 המשך שיחה', () => {
  it('מסלול שמור גובר על ההקשה הנוכחית', () => {
    // ⚠️ זה הלב: אחרי שנכנסו לחגים, הקשה "2" היא בחירה *בתוך* החגים
    // ולא מעבר ליולדות. בלי זה כל הקשה הייתה מקפיצה בין מסלולים.
    expect(resolveRoute({ [ROUTE_PARAM]: 'holiday' }, '2')).toBe('holiday')
  })

  it('נשאר במסלול גם בלי הקשה', () => {
    expect(resolveRoute({ [ROUTE_PARAM]: 'maternity' }, '')).toBe('maternity')
  })

  it('⚠️ מסלול לא מוכר נזרק — חוזרים לתפריט ולא קורסים', () => {
    expect(resolveRoute({ [ROUTE_PARAM]: 'nonsense' }, '')).toBeNull()
  })
})
