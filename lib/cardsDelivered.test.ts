import { describe, it, expect } from 'vitest'
import { cardsDelivered } from './cardsDelivered'

// ─────────────────────────────────────────────────────────────────────────────
// לוח הבקרה הציג "נמסרו 146" בעוד שנקנו 300 והמלאי 148 — כלומר 294, ושישה
// כרטיסים נעלמו מהמשוואה.
//
// השורש: הדשבורד ספר לידות עם status='active' בלבד. לידה שהושלמה
// (completed) קיבלה כרטיס שיצא מהמגירה ואינו חוזר — היא פשוט נעלמה
// מהספירה. זו אותה משפחת באגים של "נקנו": ספירת מצב *עכשווי* כתשובה
// לשאלה *מצטברת*.
//
// ⚠️ "נמסרו" הוא זהות חשבונאית — נקנו פחות מה שנשאר — ולא ספירת תיקים.
// כך הוא אינו תלוי בסטטוס הלידה, ומסך הכרטיסים והדשבורד אינם יכולים
// להיפרד זה מזה.
// ─────────────────────────────────────────────────────────────────────────────

describe('cardsDelivered', () => {
  it('🔴 הרגרסיה: 300 נקנו, 148 במלאי → 152 נמסרו (לא 146)', () => {
    expect(cardsDelivered(300, 148)).toBe(152)
  })

  it('המשוואה נסגרת תמיד: נמסרו + במלאי = נקנו', () => {
    for (const [bought, stock] of [[300, 148], [500, 12], [1000, 999]]) {
      const delivered = cardsDelivered(bought, stock)
      expect(delivered).not.toBeNull()
      expect(delivered! + stock).toBe(bought)
    }
  })

  it('טרם נרשמו רכישות — מחזיר null ולא מספר שגוי', () => {
    // ⚠️ null ולא 0: המסך מציג '—'. מספר שגוי גרוע ממקף, כי אי אפשר
    // להבחין בו.
    expect(cardsDelivered(0, 148)).toBeNull()
  })

  it('מלאי גדול מהרכישות — מצב בלתי אפשרי, לא מחזיר מספר שלילי', () => {
    expect(cardsDelivered(100, 148)).toBeNull()
  })

  it('לא נמסר דבר עדיין', () => {
    expect(cardsDelivered(300, 300)).toBe(0)
  })

  it('עמיד לערכים פגומים', () => {
    expect(cardsDelivered(NaN, 148)).toBeNull()
    expect(cardsDelivered(300, NaN)).toBeNull()
  })
})
