import { describe, it, expect } from 'vitest'

// ─────────────────────────────────────────────────────────────────────────────
// 🔴 אותו אדם נרשם פעמיים.
//
// גרינפלד מרדכי נרשם ב-12.08 כ-"23603491" וב-28.08 כ-"023603491" — אותה
// ת"ז, אותו טלפון, אותה משפחה. הרישום ניקה תווים לא-ספרתיים אך לא השלים
// אפס מוביל, ובדיקת הכפילות היא eq מדויק: המחרוזות שונות, ולכן הקיימת
// לא נמצאה.
//
// ⚠️ ת"ז ישראלית היא 9 ספרות. מי שמקליד בלי האפס המוביל מקליד את אותה
// תעודה בדיוק — ובממשק אי אפשר להבחין בין השתיים.
// ─────────────────────────────────────────────────────────────────────────────

const normId = (raw: string, isPassport = false) =>
  isPassport ? String(raw).trim() : String(raw).replace(/\D/g, '').padStart(9, '0')

/** הצורות שנבדקות מול המסד — כולל הישנה, בלי האפס. */
const variants = (clean: string, isPassport = false) =>
  Array.from(new Set(isPassport ? [clean] : [clean, clean.replace(/^0+/, '')].filter(Boolean)))

describe('🔴 נרמול ת"ז ברישום', () => {
  it('8 ספרות ו-9 ספרות מתלכדות — המקרה מהפרודקשן', () => {
    expect(normId('23603491')).toBe(normId('023603491'))
    expect(normId('23603491')).toBe('023603491')
  })

  it('ת"ז מלאה אינה משתנה', () => {
    expect(normId('312345678')).toBe('312345678')
  })

  it('מקפים ורווחים מנוקים', () => {
    expect(normId('023-603-491')).toBe('023603491')
    expect(normId(' 23603491 ')).toBe('023603491')
  })

  it('דרכון אינו מנורמל — אותיותיו משמעותיות', () => {
    expect(normId('AB1234567', true)).toBe('AB1234567')
  })
})

describe('בדיקת הכפילות מוצאת גם רשומות ישנות', () => {
  it('מחפשת את שתי הצורות', () => {
    expect(variants('023603491')).toEqual(['023603491', '23603491'])
  })

  it('🔴 נרשם ישן ללא אפס נתפס כשמזינים עם אפס', () => {
    // הרשומה במסד: "23603491". הנרשם מקליד "023603491".
    const stored = '23603491'
    expect(variants(normId('023603491'))).toContain(stored)
  })

  it('🔴 נרשם ישן ללא אפס נתפס גם כשמזינים בלי אפס', () => {
    const stored = '23603491'
    expect(variants(normId('23603491'))).toContain(stored)
  })

  it('ת"ז שאין בה אפס מוביל מחזירה צורה אחת', () => {
    expect(variants('312345678')).toEqual(['312345678'])
  })

  it('דרכון — צורה אחת בלבד', () => {
    expect(variants('AB1234567', true)).toEqual(['AB1234567'])
  })
})
