// 🔴 הבאג: Google מייצר **שני עותקים נפרדים של אותו מייל**, כל אחד עם
// message_id משלו, ובאחד מהם הצירופים חסרים לגמרי.
//
// נמדד בפועל (14 יום): 136 בקשות, מתוכן 74 הגיעו כפול, וב-17 מהן עותק
// אחד היה ריק מצירופים — כ-1 מכל 8 בקשות.
//
// ⚠️ עד היום העותק *עם* הצירופים נקלט ראשון, ולכן איש לא הבחין. זה מקרי
// לגמרי: אין שום סדר מובטח בין שני העותקים. ברגע שהריק יקדים, המשפחה
// תקבל "לא נמצא קובץ בשם ..." אחרי ששלחה את הכול — והיא לא תדע למה.
//
// ⚠️ למה לא פשוט לדלג על עותק ריק: יש בקשות שנשלחות בלי צירוף כלל
// (סיוע רפואי, אלמנה), ודילוג היה בולע אותן בשקט.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * צירוף כפי שהקליטה מקבלת אותו.
 *
 * ⚠️ url אופציונלי במכוון — כך הטיפוס מקבל גם צירוף שהגיע פגום מהספק,
 * והסינון כאן הוא זה שמסלק אותו. חתימה שדרשה url מחרוזת חסמה את הקריאה
 * מצד הקליטה, שבה השדה אופציונלי.
 */
export interface TwinAttachment {
  filename: string
  url?: string
  mimeType?: string
  size?: number
}

/**
 * משלים צירופים מהעותק התאום, אם וכאשר העותק הנוכחי ריק.
 *
 * ⚠️ ההשלמה מתבצעת **רק** כשהעותק הנוכחי ריק לחלוטין. עותק שיש בו ולו
 * צירוף אחד נשאר כפי שהוא — מיזוג של שתי רשימות חלקיות היה יוצר בקשה
 * שאיש לא שלח, ומצרף מסמכים משני מיילים שונים.
 *
 * ⚠️ צירוף בלי כתובת מסונן: הקליטה שומרת לפי ה-url, ורשומה בלי כתובת
 * רק הייתה מתחזה לצירוף קיים ומכשילה את בדיקת "נמצא קובץ בשם".
 */
export function mergeTwinAttachments(
  mine: TwinAttachment[] | null | undefined,
  twin: TwinAttachment[] | null | undefined,
): TwinAttachment[] {
  const own = (mine ?? []).filter(a => a?.url)
  if (own.length) return own

  return (twin ?? []).filter(a => a?.url)
}
