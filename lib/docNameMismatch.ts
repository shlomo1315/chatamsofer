// אזהרה כששם הקובץ סותר את סוג המסמך שנבחר.
//
// 🔴 המקרה שהוליד את זה (משפחת חנון): קובץ בשם "אישור לידה.pdf" נשמר תחת
// "ת.ז. הבעל". השם והתווית סתרו זה את זה, אף אחד לא בדק, ובמסך היולדות
// הופיע אישור לידה במקום תעודת זהות — בעוד בכרטסת הכל נראה תקין, כי שם
// מוצג שם הקובץ ולא התווית.
//
// ⚠️ אזהרה בלבד — לעולם לא חסימה. שם קובץ אינו ראיה על תוכנו:
//   • "תעודות זהות חנון.pdf" הוא קובץ מאוחד שמכיל את כל התעודות, והוא
//     לגיטימי לחלוטין תחת כל אחת מתוויות הת"ז.
//   • שמות מהסלולר (IMG_1234, scan001) אינם אומרים דבר.
// חסימה הייתה עוצרת העלאות תקינות ומאמנת את המזכירות לעקוף את ההתראה.
//
// המודול טהור: מקבל שם ותווית, מחזיר הודעה או null.
// ─────────────────────────────────────────────────────────────────────────────
import { docTypeLabel } from './docTypes'

/** משפחות מושגים שסותרות זו את זו. קובץ ששייך לאחת ומסומן כאחרת — חשוד. */
type Family = 'id' | 'birth'

// ⚠️ "תעודות" ברבים *אינו* כאן: הוא הסימן לקובץ מאוחד, שתקין תחת כל תווית.
const ID_HINTS = ['תעודת זהות', 'ת.ז', 'ת"ז', 'תז ', 'ספח']
const BIRTH_HINTS = ['אישור לידה', 'תעודת לידה', 'שחרור']

const TYPE_FAMILY: Record<string, Family> = {
  id_husband: 'id', id_husband_appx: 'id',
  id_wife: 'id', id_wife_appx: 'id',
  id_child: 'id',
  birth_cert: 'birth',
}

/**
 * מזהה סתירה מובהקת בין שם הקובץ לסוג שנבחר.
 *
 * מחזיר הודעה לתצוגה, או null כשאין סתירה ודאית.
 *
 * ⚠️ הכלל מכוון להיות *שמרני*: מתריע רק כששם הקובץ שייך בבירור למשפחת
 * מושגים אחת והתווית לאחרת. כל ספק — שותקים.
 */
export function docNameMismatch(fileName: string | null | undefined, docType: string): string | null {
  const name = (fileName ?? '').trim()
  if (!name) return null

  const expected = TYPE_FAMILY[docType]
  if (!expected) return null      // "מסמך אחר" וסוגים מותאמים — אין ציפייה

  // ⚠️ קובץ מאוחד ("תעודות זהות" ברבים) מכיל את כל התעודות ולכן תקין
  // תחת כל תווית ת"ז. זו בדיוק הצורה שבה משפחות שולחות סריקה אחת.
  if (/תעודות\s+זהות/.test(name)) return null

  const hasId = ID_HINTS.some(h => name.includes(h))
  const hasBirth = BIRTH_HINTS.some(h => name.includes(h))

  // שם שמכיל את שתי המשפחות (או אף אחת) אינו ראיה לכלום.
  if (hasId === hasBirth) return null

  const actual: Family = hasId ? 'id' : 'birth'
  if (actual === expected) return null

  const label = docTypeLabel(docType)
  const what = actual === 'birth' ? 'אישור לידה' : 'תעודת זהות'
  return `שם הקובץ נראה כמו ${what}, אך הוא נשמר תחת "${label}". לוודא שנבחר הסוג הנכון.`
}
