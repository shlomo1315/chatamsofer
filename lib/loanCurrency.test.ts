import { describe, it, expect } from 'vitest'
import { fmtLoanAmount } from './loanCurrency'

// ─────────────────────────────────────────────────────────────────────────────
// 🔴 סכומי הלוואות נקובים בדולר — בכל מקום, בלי יוצא מן הכלל.
//
// ⚠️ ההלוואה מוקלדת בדולרים (תקרת הבקשה 10,000$), אך אישורי הגמ"ח שנשלחו
// למשפחות הציגו "₪" על אותם מספרים. משפחה שקיבלה אישור על "₪5,000" קראה
// סכום שאינו קיים — לא מה שביקשה ולא מה שתקבל, פער של פי כמה.
//
// ⚠️ סיוע רפואי וחלוקות חגים *כן* בשקלים — הפונקציה הזו להלוואות בלבד,
// ואסור להחיל אותה עליהם.
//
// 🔴 הסימן לפני המספר ($5,000 ולא 5,000$) — כך זה בכל מסכי ההלוואות.
// ─────────────────────────────────────────────────────────────────────────────

describe('🔴 fmtLoanAmount — דולר בלבד', () => {
  it('מציג סימן דולר לפני המספר', () => {
    expect(fmtLoanAmount(5000)).toBe('$5,000')
  })

  it('🔴 לעולם לא שקל', () => {
    for (const n of [0, 1, 1500, 10000]) {
      expect(fmtLoanAmount(n)).not.toContain('₪')
      expect(fmtLoanAmount(n)).not.toContain('ש"ח')
    }
  })

  // ⚠️ מפרידי אלפים באנגלית: he-IL מוסיף תווי כיווניות שנשברים במייל
  // ובקובץ אקסל, והמספר נראה הפוך.
  it('מפריד אלפים בפסיק', () => {
    expect(fmtLoanAmount(1234567)).toBe('$1,234,567')
  })

  it('מעגל לשלם — אין אגורות בהלוואה', () => {
    expect(fmtLoanAmount(1500.4)).toBe('$1,500')
    expect(fmtLoanAmount(1500.6)).toBe('$1,501')
  })

  // ⚠️ ריק ולא "$0": שדה שטרם אושר אינו הלוואה על סכום אפס.
  it('null/undefined מחזירים מחרוזת ריקה', () => {
    expect(fmtLoanAmount(null)).toBe('')
    expect(fmtLoanAmount(undefined)).toBe('')
  })

  it('אפס מפורש כן מוצג', () => {
    expect(fmtLoanAmount(0)).toBe('$0')
  })

  it('ערך לא מספרי אינו מייצר NaN', () => {
    expect(fmtLoanAmount(Number('x'))).toBe('$0')
  })
})
