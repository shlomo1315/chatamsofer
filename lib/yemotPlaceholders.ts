// 🔴 מה שקרה בפועל: הנוסח card_ready במסד הוא "הכרטיס שלכם מוכן לאיסוף
// במוקד {center}", אך הקוד קרא לו *בלי* להעביר ערך — כי שם המוקד נאמר
// בטוקן נפרד מיד אחריו (spokenCenterDetails, או הקלטה אנושית של המוקד).
// ימות הקריאה את מה שקיבלה, והמשפחות שמעו "מוכן לאיסוף במוקד סוגריים
// סנטר סוגריים" — בדיוק בשיחה שבה הן מבררות לאן ללכת.
//
// ⚠️ מסירים ולא משאירים: הערך כבר נאמר בהמשך ההודעה. חור קטן במשפט נשמע
// כהפסקה טבעית; שם המשתנה נשמע כתקלה.
//
// ⚠️ הניקוי רץ *אחרי* ההחלפה, ולכן אינו פוגע בשדות שכן קיבלו ערך —
// {name}, {distribution}, {card}, {reason} וכל השאר ממשיכים לעבוד.
// ─────────────────────────────────────────────────────────────────────────────

/** שדה בנוסח: אותיות לועזיות, ספרות וקו תחתון בין סוגריים מסולסלים. */
const PLACEHOLDER_RE = /\{[a-z0-9_]+\}/gi

/**
 * מסיר שדות שנותרו ללא ערך.
 *
 * ⚠️ מוחלף ברווח ולא במחרוזת ריקה: "במוקד{center}." היה נדבק למילה הבאה.
 * הרווחים הכפולים שנוצרים מתכווצים ב-tts שרץ אחר כך.
 */
export function stripUnfilledPlaceholders(text: string): string {
  return String(text ?? '').replace(PLACEHOLDER_RE, ' ')
}

/**
 * האם נותר בטקסט שדה שלא הוחלף.
 *
 * ⚠️ ביטוי חדש בכל קריאה, ולא PLACEHOLDER_RE: ביטוי עם דגל g שומר lastIndex
 * בין קריאות ל-test, כך שאותו טקסט היה מחזיר לסירוגין true ו-false.
 */
export function hasUnfilledPlaceholder(text: string): boolean {
  return /\{[a-z0-9_]+\}/i.test(String(text ?? ''))
}
