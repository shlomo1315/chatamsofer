/** הדומיין שלנו — כל כתובת בו היא שלנו, גם בלי רשימה. */
const OUR_DOMAIN = '@chasamsofer.info'

/**
 * האם הכתובת היא תיבה שלנו.
 *
 * @param mailboxes כתובות התיבות המחוברות (gmail_accounts.email)
 *
 * ⚠️ ההשוואה מדויקת ולא "מכיל": חסימה רחבה מדי הייתה משתיקה בקשות
 * אמיתיות ממשפחות בלי שאיש יידע שהן הגיעו.
 */
export function isOurMailbox(
  from: string | null | undefined,
  mailboxes: readonly string[],
): boolean {
  const addr = String(from ?? '').trim().toLowerCase()
  if (!addr) return false
  // ⚠️ endsWith ולא includes: "x@chasamsofer.info.evil.com" אינו שלנו.
  if (addr.endsWith(OUR_DOMAIN)) return true
  return mailboxes.some(m => String(m ?? '').trim().toLowerCase() === addr)
}
