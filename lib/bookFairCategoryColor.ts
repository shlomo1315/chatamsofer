// עם נפילה לגוון הבורדו של המותג כשהשם לא מוכר.

export type CategoryColor = {
  /** הגוון המלא — קו הכותרת, הנקודה, המק"ט, כפתור ההוספה. */
  main: string
  /** אותו גוון ברקע עדין מאוד — תגיות, הילה מאחורי הכריכה. */
  soft: string
}

// 🔴 הפלטה נגזרת מהלוגו ולא נבחרה חופשית.
//
// דגימת public/logo.png מחזירה שני צבעים שולטים: כחול־לילה עמוק
// (#101030 עד #202050) וזהב (#E0C090 עד #F0D090). הגוונים כאן נעים
// סביב הכחול הזה — מכחול דיו ועד טורקיז ואינדיגו — ושומרים על אותה
// עומק. ⚠️ הסגול, הבורדו, הענבר והזית שהיו כאן קודם אינם בלוגו
// בכלל, והדף נראה כאילו הוא שייך למותג אחר.

/** ברירת המחדל: הכחול של הלוגו. קטגוריה חדשה תיראה שייכת מיד. */
export const DEFAULT_CATEGORY_COLOR: CategoryColor = { main: '#1B2A5B', soft: '#EAEDF5' }

