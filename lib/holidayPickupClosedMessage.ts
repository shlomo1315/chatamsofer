// איזו הודעה נשמעת כשחלוקת הכרטיסים סגורה.
//
// 🔴 שער אחד סגור — שני משפטים הפוכים:
//   • לפני שהחלוקה החלה  → "עדיין לא נפתחה"  (המתן להודעה)
//   • אחרי שהסתיימה      → "כבר הסתיימה"      (המועד עבר)
//
// ⚠️ עד כה נשמע "עדיין לא נפתחה" גם אחרי הסיום. מי שאיחר הבין שעליו
// להמתין להודעה שלא תגיע לעולם, ולא ידע שהחלוקה נגמרה — והמשרד קיבל
// שיחות של משפחות שממתינות לשווא.
//
// 🔴 ההבחנה אינה בתאריך אלא בעובדה: האם כבר חולק ולו כרטיס אחד. חלוקה
// שנסגרה בלי שאיש אסף מעולם היא "טרם נפתחה" גם אם המועד חלף.
// ─────────────────────────────────────────────────────────────────────────────

/** מפתח ההודעה שתושמע. */
export type PickupClosedKey = 'card_pickup_closed' | 'card_pickup_ended'

export function pickupClosedMessageKey(opts: {
  /** האם שער האיסוף פתוח. */
  pickupOpen: boolean
  /** האם כבר חולקו כרטיסים בפועל (מוקד כלשהו עם pickup_open_at). */
  everStarted: boolean
}): PickupClosedKey | null {
  // שער פתוח — אין הודעת סגירה כלל.
  if (opts.pickupOpen) return null
  return opts.everStarted ? 'card_pickup_ended' : 'card_pickup_closed'
}
