import { describe, it, expect } from 'vitest'
import { recoveryRange, shouldJumpMonth } from './recoveryRange'

// ─────────────────────────────────────────────────────────────────────────────
// 🔴 טווח ימי ההחלמה שחוצה חודש.
//
// מה שנצפה: ביום האחרון של החודש הלועזי, סימון "היום" מסמן גם את יום
// המחרת — אבל המחרת נופל בחודש הבא, והלוח נשאר על החודש הנוכחי. היולדת
// רואה תא אחד מסומן בלבד ומניחה שהסימון נכשל.
//
// ⚠️ החישוב עצמו תמיד היה נכון (חיבור מילישניות עובר חודשים ושנים).
// מה שחסר הוא קפיצת התצוגה.
// ─────────────────────────────────────────────────────────────────────────────

describe('recoveryRange — הטווח', () => {
  it('זכאות 2 ימים = הגעה + יום אחד', () => {
    const r = recoveryRange('2026-08-20', 2)
    expect(r).toEqual({ from: '2026-08-20', to: '2026-08-21' })
  })

  it('🔴 סוף חודש — היציאה בחודש הבא', () => {
    const r = recoveryRange('2026-08-31', 2)
    expect(r).toEqual({ from: '2026-08-31', to: '2026-09-01' })
  })

  it('🔴 סוף שנה — עובר גם שנה', () => {
    const r = recoveryRange('2026-12-31', 2)
    expect(r).toEqual({ from: '2026-12-31', to: '2027-01-01' })
  })

  it('⚠️ תאומים (4 ימים) מסוף החודש', () => {
    const r = recoveryRange('2026-08-30', 4)
    expect(r).toEqual({ from: '2026-08-30', to: '2026-09-02' })
  })

  it('⚠️ פברואר מעוברת — 29 בפברואר קיים ב-2028', () => {
    expect(recoveryRange('2028-02-28', 2)).toEqual({ from: '2028-02-28', to: '2028-02-29' })
  })

  it('זכאות יום אחד — הגעה בלבד', () => {
    expect(recoveryRange('2026-08-31', 1)).toEqual({ from: '2026-08-31', to: '2026-08-31' })
  })
})

describe('shouldJumpMonth — 🔴 קפיצת התצוגה', () => {
  it('היציאה בחודש אחר → קופצים אליו', () => {
    expect(shouldJumpMonth('2026-09-01', new Date(2026, 7, 1))).toBe(true)
  })

  it('היציאה באותו חודש → נשארים', () => {
    expect(shouldJumpMonth('2026-08-21', new Date(2026, 7, 1))).toBe(false)
  })

  it('⚠️ אותו מספר חודש בשנה אחרת → כן קופצים', () => {
    // ינואר 2027 מול ינואר 2026 — בלי בדיקת השנה זה היה נראה זהה.
    expect(shouldJumpMonth('2027-01-01', new Date(2026, 0, 1))).toBe(true)
  })

  it('תאריך פגום אינו מקפיץ', () => {
    expect(shouldJumpMonth('', new Date(2026, 7, 1))).toBe(false)
    expect(shouldJumpMonth('לא-תאריך', new Date(2026, 7, 1))).toBe(false)
  })
})
