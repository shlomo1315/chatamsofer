// שהתבקשו פחות מסמכים.
// ─────────────────────────────────────────────────────────────────────────────

import { docTypeLabel, type DocTypeOption } from './docTypes'

/**
 * @param types רשימת הסוגים מההגדרות. ברירת המחדל מכסה את סוגי הליבה.
 */
export function docKeysToHebrew(
  raw: string | null | undefined,
  types?: DocTypeOption[],
): string {
  return String(raw ?? '')
    .split(',')
    .map(s => s.trim())
    .filter(Boolean)
    // ⚠️ docTypeLabel מחזיר את המפתח עצמו כשאינו מוכר — וזו ההתנהגות
    // הרצויה כאן.
    .map(k => docTypeLabel(k, types))
    .join(' · ')
}
