// צבע הדור לפי הייחוס המאושר — הכלל היחיד ל-5 הדורות הראשונים.
//
// 🔴 עד דור 5: מי שבטבלה המאושרת ירוק, כל השאר אדום. נקודה.
//
// ⚠️ עד היום הצבע נקבע לפי *התווית* שהודבקה על הצומת (status='verified')
// ולא לפי הקובץ. lineage_approved_ref יושבת במסד מאז 25.08 ומעולם לא
// נקראה מהקוד — ולכן 51 צמתים שסומנו ידנית נצבעו ירוק אף שאינם בקובץ,
// והצבעים אמרו את ההפך מהאמת.
//
// ⚠️ המקרה שחשף זאת: "רבי יהושע צבי גולדגלנץ" יושב בעץ בדור 3 כבן של
// הכתב סופר. בקובץ המאושר הוא דור 5, דרך דויטש — נין ולא בן, ובירוק.
//
// 🔴 ההשוואה כוללת את הדור: אותו שם בדור אחר הוא ייחוס שגוי ולא התאמה.
// זה בדיוק ההבדל בין "השם מוכר" לבין "האדם הזה יושב במקום הנכון".
//
// ⚠️ מעל דור 5 הכלל אינו חל: שם הנרשם מוסיף את אבותיו בעצמו, וזה המצב
// הרגיל והצפוי. אדום שם היה מתריע על כל משפחה במערכת.
// ─────────────────────────────────────────────────────────────────────────────

import { EARLY_DEPTH, type GenStatus, type GenColor } from './lineageDeviation'

/** האם קיים בקובץ המאושר — לפי שם *ודור* גם יחד. */
export function isInApprovedRef(
  name: string,
  generation: number,
  inRef: (name: string, generation: number) => boolean,
): boolean {
  const nm = String(name ?? '').trim()
  if (!nm) return false
  return inRef(nm, generation)
}

/**
 * צבע הדור.
 *
 * 🔴 דור 1 הוא החתם סופר עצמו — תמיד ירוק.
 * 🔴 דורות 2–5 — הקובץ המאושר מכריע, והתווית אינה נשקלת כלל.
 * ⚠️ מעל דור 5 — התווית חוזרת להכריע, כי אין קובץ להשוות מולו.
 * ⚠️ rejected אדום בכל דור: זו החלטה מפורשת לדחות.
 */
export function genColorByRef(
  generation: number,
  name: string,
  status: GenStatus,
  inRef: (name: string, generation: number) => boolean,
): GenColor {
  if (generation <= 1) return 'green'
  if (status === 'rejected') return 'red'

  // ─────────────────────────────────────────────────────────────────────────
  // 🔴 הקובץ המאושר הוא המכריע — לא התווית ולא approval_source.
  //
  // ⚠️ approval_source='legacy' נבדק ונפסל כקריטריון: גולדגלנץ ורוזנבוים
  // מסומנים legacy אף שהם יושבים בדור 3 במקום 5 ו-4. מישהו סימן אותם
  // ידנית, והסימון אינו מעיד שהם באמת הגיעו מהאקסל *באותו דור*.
  //
  // ⚠️ ההשוואה כוללת את הדור: אותו שם בדור אחר הוא ייחוס שגוי ולא התאמה.
  // ─────────────────────────────────────────────────────────────────────────
  if (generation <= EARLY_DEPTH) {
    return isInApprovedRef(name, generation, inRef) ? 'green' : 'red'
  }

  // מעל הליבה המאושרת — כמו קודם.
  return status === 'verified' ? 'green' : 'orange'
}
