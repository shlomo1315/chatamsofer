import { describe, it, expect } from 'vitest'
import { hebrewNumbersToDigits as h } from './hebrewNumbers'

describe('hebrewNumbersToDigits — כתובות מתומללות', () => {
  // 🔴 הדוגמה של המשתמש (08.10)
  it('רחוב מלכי ישראל עשרים ושתיים → מלכי ישראל 22', () => {
    expect(h('רחוב מלכי ישראל עשרים ושתיים')).toBe('מלכי ישראל 22')
  })

  it('יחידות, עשרות ומאות', () => {
    expect(h('הרב קוק חמש')).toBe('הרב קוק 5')
    expect(h('סוקולוב אחת עשרה')).toBe('סוקולוב 11')
    expect(h('רבי עקיבא מאה עשרים ושלוש')).toBe('רבי עקיבא 123')
    expect(h('ז\'בוטינסקי שלוש מאות וחמישים')).toBe('ז\'בוטינסקי 350')
    expect(h('השומר עשרים ואחת')).toBe('השומר 21')
  })

  it('דירה וקומה — כל מספר בנפרד', () => {
    expect(h('חזון איש שלושים ושבע דירה שתיים')).toBe('חזון איש 37 דירה 2')
    expect(h('דסלר ארבע קומה שלוש דירה תשע')).toBe('דסלר 4 קומה 3 דירה 9')
  })

  it('פיסוק נשמר ומפריד', () => {
    expect(h('רבי עקיבא עשרים, דירה שש')).toBe('רבי עקיבא 20, דירה 6')
  })

  it('ספרות שכבר קיימות לא משתנות', () => {
    expect(h('מלכי ישראל 22 דירה 3')).toBe('מלכי ישראל 22 דירה 3')
  })

  // 🔴 שמות מקומות — המרה עיוורת הייתה שולחת חבילה למקום אחר
  it('שמות מקומות שמכילים מספר נשמרים', () => {
    expect(h('באר שבע')).toBe('באר שבע')
    expect(h('קריית שמונה')).toBe('קריית שמונה')
    expect(h('מאה שערים עשר')).toBe('מאה שערים 10')
    expect(h('אחד העם שלוש')).toBe('אחד העם 3')
  })

  it('"ברחוב" בתחילה והסרה אחרי פסיק', () => {
    expect(h('ברחוב יונה הנביא שש')).toBe('יונה הנביא 6')
    expect(h('בני ברק, רחוב חזון איש עשר')).toBe('בני ברק, חזון איש 10')
  })

  it('ריק ו-null לא נופלים', () => {
    expect(h('')).toBe('')
  })
})
