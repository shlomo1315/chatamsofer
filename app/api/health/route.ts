import { NextResponse } from 'next/server'

export const dynamic = 'force-dynamic'

// ─────────────────────────────────────────────────────────────────────────────
// בדיקת חיוּת לפריסה (Railway healthcheckPath).
//
// 🔴 למה זה קריטי: בלי נתיב בדיקה Railway מפנה תעבורה למכולה החדשה ברגע
// שהתהליך עלה — עוד לפני ש-Next סיים להתחמם ולהיות מסוגל להגיש בקשות.
// התוצאה היא חלון של דקה-שתיים בכל פריסה שבו האתר מחזיר שגיאות, וזה בדיוק
// מה שנראה למשתמש כ"הכל קרס". עם healthcheck המכולה הישנה ממשיכה להגיש עד
// שהחדשה עונה כאן בהצלחה — פריסה בלי הפסקה.
//
// ⚠️ בכוונה בלי גישה למסד: הבדיקה אמורה לענות על "האם השרת מסוגל להגיש
// בקשות", ולא על "האם Supabase זמין". תקלה רגעית במסד הייתה מכשילה את
// הבדיקה, מונעת את הפריסה, ומשאירה גרסה ישנה באוויר בלי סיבה.
// ─────────────────────────────────────────────────────────────────────────────
// ─────────────────────────────────────────────────────────────────────────────
// 🔴 מזהה הגרסה — הדפדפן משווה מולו כדי לדעת שעלתה פריסה חדשה.
//
// ⚠️ נקבע פעם אחת בעליית התהליך: מכולה חדשה = ערך חדש, וזה בדיוק האות
// שהלקוח מחפש. RAILWAY_DEPLOYMENT_ID קיים בפריסה אמיתית; בפיתוח אין
// כזה, ולכן נפילה-לאחור לזמן העלייה.
//
// ⚠️ אינו משתנה בין בקשות באותה מכולה — אחרת כל קריאה הייתה נראית
// כפריסה חדשה, והבאנר היה מהבהב לנצח.
// ─────────────────────────────────────────────────────────────────────────────
const BUILD_ID = process.env.RAILWAY_DEPLOYMENT_ID || `dev-${Date.now()}`

export async function GET() {
  return NextResponse.json(
    { ok: true, at: new Date().toISOString(), build: BUILD_ID },
    { headers: { 'Cache-Control': 'no-store' } },
  )
}
